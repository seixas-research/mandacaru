//! The strain directions of the stress contraction (`periodic::stress_terms::directions`): the
//! number of independent invariant symmetric tensors of each crystal family, the orthonormality and
//! invariance of the basis, and that projecting a full tensor on it is the symmetrized group
//! average (the reason the contraction may stop at `n` tangents).
use mandacaru_core::periodic::{point_group::PointGroup, stress_terms::Directions};
use nalgebra::{Matrix3, Vector3};

fn rotation(axis: [f64; 3], turns: f64) -> Matrix3<f64> {
    nalgebra::Rotation3::from_axis_angle(
        &nalgebra::Unit::new_normalize(Vector3::from(axis)),
        2. * std::f64::consts::PI * turns,
    )
    .into_inner()
}

/// The group generated by `generators`, closed under products.
fn group(generators: &[Matrix3<f64>]) -> PointGroup {
    let mut elements = vec![Matrix3::identity()];
    let mut next = 0;
    while next < elements.len() {
        for g in generators {
            let product = g * elements[next];
            if !elements.iter().any(|e| (e - product).norm() < 1e-9) {
                elements.push(product);
            }
        }
        next += 1;
    }
    let maps = vec![vec![0]; elements.len()];
    PointGroup::from_parts(elements, maps)
}

fn inversion() -> Matrix3<f64> {
    -Matrix3::identity()
}

fn families() -> Vec<(&'static str, PointGroup, usize, usize)> {
    let z = [0., 0., 1.];
    let x = [1., 0., 0.];
    let y = [0., 1., 0.];
    vec![
        (
            "cubic Oh",
            group(&[
                rotation(z, 0.25),
                rotation([1., 1., 1.], 1. / 3.),
                inversion(),
            ]),
            48,
            1,
        ),
        (
            "hexagonal D6h",
            group(&[rotation(z, 1. / 6.), rotation(x, 0.5), inversion()]),
            24,
            2,
        ),
        (
            "trigonal D3d (Bi2Se3)",
            group(&[rotation(z, 1. / 3.), rotation(x, 0.5), inversion()]),
            12,
            2,
        ),
        (
            "tetragonal D4h",
            group(&[rotation(z, 0.25), rotation(x, 0.5), inversion()]),
            16,
            2,
        ),
        (
            "orthorhombic D2h",
            group(&[rotation(x, 0.5), rotation(y, 0.5), inversion()]),
            8,
            3,
        ),
        (
            "monoclinic C2h",
            group(&[rotation(y, 0.5), inversion()]),
            4,
            4,
        ),
        ("triclinic Ci", group(&[inversion()]), 2, 6),
    ]
}

fn dot(a: &[[f64; 3]; 3], b: &[[f64; 3]; 3]) -> f64 {
    (0..9).map(|i| a[i / 3][i % 3] * b[i / 3][i % 3]).sum()
}

fn matrix(t: &[[f64; 3]; 3]) -> Matrix3<f64> {
    Matrix3::from_fn(|a, b| t[a][b])
}

/// A tensor with no symmetry of its own.
fn generic() -> [[f64; 3]; 3] {
    [
        [0.31, -0.72, 0.18],
        [0.44, 0.97, -0.51],
        [-0.23, 0.66, 0.12],
    ]
}

#[test]
fn each_crystal_family_has_its_number_of_invariant_strain_directions() {
    for (name, group, operations, n) in families() {
        assert_eq!(group.len(), operations, "{name}: the generated group");
        let directions = Directions::invariant(Some(&group)).unwrap();
        assert_eq!(directions.len(), n, "{name}");
    }
    assert_eq!(Directions::invariant(None).unwrap().len(), 6);
}

#[test]
fn the_invariant_basis_is_orthonormal_symmetric_and_invariant() {
    for (name, group, _, _) in families() {
        let directions = Directions::invariant(Some(&group)).unwrap();
        let basis = directions.as_slice();
        for (i, e) in basis.iter().enumerate() {
            for (j, f) in basis.iter().enumerate() {
                let want = if i == j { 1. } else { 0. };
                assert!((dot(e, f) - want).abs() < 1e-12, "{name}: Gram ({i},{j})");
            }
            let m = matrix(e);
            assert!((m - m.transpose()).norm() < 1e-12, "{name}: symmetric");
            for r in group.rotations() {
                assert!(
                    (r * m * r.transpose() - m).norm() < 1e-12,
                    "{name}: invariant"
                );
            }
        }
    }
}

#[test]
fn projecting_on_the_basis_is_the_symmetrized_group_average() {
    let g = generic();
    for (name, group, _, _) in families() {
        let mut average = g;
        group.tensor(&mut average);
        let want = (matrix(&average) + matrix(&average).transpose()) * 0.5;
        let got = matrix(&Directions::invariant(Some(&group)).unwrap().project(&g));
        assert!(
            (got - want).norm() < 1e-12,
            "{name}: {}",
            (got - want).norm()
        );
    }
    // Without operations: the symmetric part.
    let got = matrix(&Directions::invariant(None).unwrap().project(&g));
    let want = (matrix(&g) + matrix(&g).transpose()) * 0.5;
    assert!((got - want).norm() < 1e-12);
}

#[test]
fn the_nine_unit_directions_reproduce_every_entry_and_average_over_the_group() {
    let all = Directions::all_entries(None);
    assert_eq!(all.len(), 9);
    assert!(all.is_all_entries());
    let g = generic();
    assert_eq!(all.project(&g), g);
    let (_, trigonal, _, _) = families().remove(2);
    let averaged = Directions::all_entries(Some(trigonal.clone()));
    let mut want = g;
    trigonal.tensor(&mut want);
    let got = averaged.project(&g);
    for a in 0..3 {
        for b in 0..3 {
            assert!((got[a][b] - want[a][b]).abs() < 1e-14);
        }
    }
}
