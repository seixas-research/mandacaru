/// The criterion on the shipped branches of Na, Ne and Fe: no extra state in any branch.
#[test]
fn the_branches_of_the_light_fully_relativistic_elements_hold_no_ghost() {
    for element in ["Na", "Ne", "Fe"] {
        let ctx = context();
        let ds = read(&ctx, &dataset_path("lda-fr", element));
        let set = branches(&ctx, &ds).unwrap();
        let ghosts = branch_ghost_errors(&ctx, &set).unwrap();
        assert!(ghosts.is_empty(), "{element}: {ghosts:?}");
    }
}

/// A Gaussian well of `depth` Hartree and 1/e radius 0.45 Bohr added to the local potential.
fn add_well(smooth: &mut mandacaru_core::paw::diagnose::view::Smooth, depth: f64) {
    let r = smooth.r.as_slice().to_vec();
    for (v, r) in smooth.v_local_screened.as_mut_slice().iter_mut().zip(r) {
        *v -= depth * (-(r / 0.45).powi(2)).exp();
    }
}

/// The criterion on a branch that does hold a ghost: sodium's p branches (`j = 1/2, 3/2`) with a
/// Gaussian well of 34.7 Ha added to the local potential bind an extra state about 4.5 Ha down.
/// The oracle of its depth is the dense generalized solve of the same matrices (A5), which the
/// separable solver the criterion reads equals to 3e-12 Ha on a common grid; the criterion's own
/// box and extrapolation agree with it to 2 percent of the depth. The scalar criterion (which
/// reads `j`-averaged channels only, as the generator did) finds nothing in the branch set and
/// misses a ghost 4e4 tolerances deep, and the untouched branches hold none.
#[test]
fn a_deep_well_binds_a_ghost_in_every_branch_the_criterion_finds_and_the_scalar_one_misses() {
    let ctx = context();
    let ds = read(&ctx, &dataset_path("lda-fr", "Na"));
    let mut set = branches(&ctx, &ds).unwrap();
    assert!(branch_ghost_errors(&ctx, &set).unwrap().is_empty());
    add_well(&mut set, 34.7);
    let found = branch_ghost_errors(&ctx, &set).unwrap();
    eprintln!("Na p branches with the well: {found:?}");
    let grid = mandacaru_core::paw::diagnose::spectrum::nodes(8., 0.02);
    for kappa in [-2, 1] {
        let key = Key {
            l: 1,
            kappa: Some(kappa),
        };
        let channel = &set.channels[&key];
        let dense = dense_levels(&ctx, &set, channel, &grid, 1)[0] - channel.energies[0];
        let depth = *found
            .get(&key)
            .unwrap_or_else(|| panic!("no ghost found in {key:?}"));
        eprintln!("kappa {kappa}: criterion {depth:+.5} Ha, dense solve {dense:+.5} Ha");
        assert!(
            (depth - dense).abs() < 0.02 * dense.abs(),
            "kappa {kappa}: {depth} against the dense {dense}"
        );
        assert!(-depth / GHOST_TOLERANCE > 1e4);
    }
    assert_eq!(found.len(), 2, "{found:?}");
    // The control: the scalar criterion on the branch set sees nothing.
    assert!(ghost_errors(&ctx, &set, None).unwrap().is_empty());
}

/// Lead, shipped lda-fr: no branch holds a ghost (the stored `level_errors` of its p branches are
/// -2.3e-3 and -4.3e-6 Ha), and the empty f branches sit 0.21 Ha below their scattering
/// reference, the box continuum following the wall, which is no ghost and is not reported. The
/// wrong criterion, "any branch whose level error is below -GHOST_TOLERANCE", flags both f
/// branches (2,000 tolerances) and is compared with the oracle. A dataset *generated today* for
/// lead is different: its `j = 3/2` p branch binds a ghost 3.7363 Ha below the reference (the
/// live Python generator, `PB_PYTHON_LEVEL_ERRORS`, and the Rust one, `paw_search.rs`), which the
/// shipped file (generated earlier) does not have.
#[test]
fn the_shipped_lead_has_no_branch_ghost_and_its_empty_f_branches_are_not_ghosts() {
    let ctx = context();
    let ds = read(&ctx, &dataset_path("lda-fr", "Pb"));
    let set = branches(&ctx, &ds).unwrap();
    let ghosts = branch_ghost_errors(&ctx, &set).unwrap();
    assert!(ghosts.is_empty(), "{ghosts:?}");
    let levels = level_errors(&ctx, &ds).unwrap();
    let stored_p = ds.spin_orbit[&1].level_errors.data();
    eprintln!(
        "Pb shipped: p level errors recomputed {:?}, stored {stored_p:?}; Python regenerated {:?}",
        levels[&1], PB_PYTHON_LEVEL_ERRORS[1]
    );
    // The shipped p branches are within the stride-4 floor of their stored levels, and nowhere
    // near today's j = 3/2 level.
    assert!((levels[&1][1] - stored_p[1]).abs() <= LEVEL_GATE);
    assert!(stored_p[1] > -1e-3 && PB_PYTHON_LEVEL_ERRORS[1][1] < -3.0);
    // The f branches: -0.21 Ha, a scattering reference, no ghost.
    let f = levels[&3];
    assert!(f.iter().all(|e| *e < -0.15), "f level errors {f:?}");
    let wrong = levels
        .iter()
        .flat_map(|(l, e)| e.iter().map(move |e| (*l, *e)))
        .filter(|(_, e)| *e < -GHOST_TOLERANCE)
        .filter(|(l, _)| *l == 3)
        .count();
    assert_eq!(wrong, 2, "the level-error criterion flags both f branches");
    assert!(f[0].abs() / GHOST_TOLERANCE > 1e3);
}

/// The record keeps what the diagnosis finds: a branch ghost has its own key, written only when
/// there is one (every older file round-trips unchanged), read back, and the recording rule of
/// the generator (a ghosted dataset records the ghosts alone) holds for the branch ghosts too.
#[test]
fn a_branch_ghost_and_a_missing_state_have_keys_in_the_record() {
    use mandacaru_core::paw::diagnose::Diagnosis;
    use mandacaru_core::paw::record::{Defects, PawDataset, WriteSpec};
    let ctx = context();
    let mut ds = read(&ctx, &dataset_path("lda-fr", "Na"));
    let diagnosis = Diagnosis {
        branch_ghosts: [(
            Key {
                l: 1,
                kappa: Some(-2),
            },
            -3.74,
        )]
        .into(),
        phases: [(Key { l: 1, kappa: None }, [0.9, 0.9])].into(),
        ..Diagnosis::default()
    };
    // The ghost alone is recorded: the wrong phase of the same diagnosis is not.
    let defects = diagnosis.defects();
    assert_eq!(defects.branch_ghosts[&Defects::branch_key(1, -2)], -3.74);
    assert!(defects.phases.is_empty() && defects.missing.is_empty());
    let missing = Diagnosis {
        missing: [(3, 0.0173)].into(),
        ..Diagnosis::default()
    };
    assert_eq!(missing.defects().missing[&3], 0.0173);
    assert!(!missing.is_clean() && !diagnosis.is_clean());
    ds.defects = Defects {
        missing: [(3, 0.0173)].into(),
        branch_ghosts: defects.branch_ghosts.clone(),
        ..Defects::default()
    };
    let dir = std::env::temp_dir().join(format!("mandacaru_defect_keys_{}", std::process::id()));
    std::fs::create_dir_all(&dir).unwrap();
    let path = dir.join("Na.parquet");
    ds.write(
        &ctx,
        &path,
        &WriteSpec {
            stride: 4,
            codec: mandacaru_core::parquet::Codec::Zstd,
        },
    )
    .unwrap();
    let back = PawDataset::read(&ctx, &path).unwrap();
    std::fs::remove_dir_all(&dir).unwrap();
    assert_eq!(back.defects, ds.defects);
}

/// The plan's full-resolution gate for the branch levels: on the in-memory dataset of the Dirac
/// chain (A4), whose tables are the generation grid and not the stride-4 table of a file, the
/// level of a branch recomputed by the diagnostics from the blocks equals the level the
/// generator recorded. The shipped files cannot show this (the same levels agree to 1.4e-4 Ha
/// at worst, `LEVEL_GATE`: where the sphere edge falls between table nodes); the generated
/// dataset does, to the floor of the two solves.
#[test]
fn the_branch_levels_of_a_generated_dataset_are_the_recorded_ones_at_full_resolution() {
    const FULL_RESOLUTION_GATE: f64 = 1e-9;
    let loaded = paw_spin_orbit_support::loaded("lda-fr_Na");
    let ds = &loaded.generated.dataset;
    let levels = level_errors(&loaded.ctx, ds).unwrap();
    let mut worst = 0f64;
    for (l, so) in &ds.spin_orbit {
        for (b, &recorded) in so.level_errors.data().iter().enumerate() {
            let got = levels[&(*l as usize)][b];
            eprintln!("Na l={l} branch {b}: recorded {recorded:+.12e}, recomputed {got:+.12e}");
            worst = nan_max(worst, (got - recorded).abs());
        }
    }
    eprintln!("Na: full-resolution branch levels agree to {worst:.3e} Ha");
    assert!(worst <= FULL_RESOLUTION_GATE, "{worst:e}");
}
