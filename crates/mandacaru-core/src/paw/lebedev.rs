fn expand_seed(seed: [f64; 3]) -> Vec<Vector3<f64>> {
    let [a, b, c] = seed;
    let raw = [
        [a, b, c],
        [a, c, b],
        [b, a, c],
        [b, c, a],
        [c, a, b],
        [c, b, a],
    ];
    let mut perms: Vec<[f64; 3]> = Vec::with_capacity(6);
    for p in raw {
        if !perms.contains(&p) {
            perms.push(p);
        }
    }
    let signs = |v: f64| -> &'static [f64] {
        if v == 0.0 {
            &[0.0]
        } else {
            &[-1.0, 1.0]
        }
    };
    let mut points = Vec::new();
    for p in perms {
        for &sx in signs(p[0]) {
            let x = sx * p[0];
            for &sy in signs(p[1]) {
                let y = sy * p[1];
                for &sz in signs(p[2]) {
                    points.push(Vector3::new(x, y, sz * p[2]));
                }
            }
        }
    }
    points
}

fn is_signed_permutation(m: &Matrix3<f64>) -> bool {
    let mut row_used = [false; 3];
    for col in 0..3 {
        let mut best_row = 0;
        let mut best_abs = -1.0;
        let mut rest = 0.0;
        for row in 0..3 {
            let a = m[(row, col)].abs();
            if a > best_abs {
                if best_abs > 0.0 {
                    rest += best_abs;
                }
                best_abs = a;
                best_row = row;
            } else {
                rest += a;
            }
        }
        if (best_abs - 1.0).abs() > 0.05 || rest > 0.05 || row_used[best_row] {
            return false;
        }
        row_used[best_row] = true;
    }
    true
}

/// If `operations` is an octahedral ($O_h$, order 48) group, returns its smooth orthonormal
/// cubic frame `[u1, u2, u3]` matching the operation set; returns `None` otherwise.
pub(super) fn octahedral_frame(operations: &[Matrix3<f64>]) -> Option<Matrix3<f64>> {
    if operations.len() != 48 {
        return None;
    }
    // In O_h, the 6 proper C_4 rotations are uniquely identified by det > 0 and trace = 1.
    let mut axes: Vec<Vector3<f64>> = Vec::with_capacity(6);
    for g in operations {
        if g.determinant() > 0.5 && (g.trace() - 1.0).abs() < 0.5 {
            let axis = Vector3::new(
                g[(2, 1)] - g[(1, 2)],
                g[(0, 2)] - g[(2, 0)],
                g[(1, 0)] - g[(0, 1)],
            );
            let norm = axis.norm();
            if norm < 0.5 {
                return None;
            }
            axes.push(axis / norm);
        }
    }
    if axes.len() != 6 {
        return None;
    }
    let u1 = axes.iter().copied().max_by(|a, b| a[0].total_cmp(&b[0]))?;
    let u2 = axes
        .iter()
        .copied()
        .filter(|v| v.dot(&u1).abs() < 0.5)
        .max_by(|a, b| a[1].total_cmp(&b[1]))?;
    let u3 = axes
        .iter()
        .copied()
        .filter(|v| v.dot(&u1).abs() < 0.5 && v.dot(&u2).abs() < 0.5)
        .max_by(|a, b| a[2].total_cmp(&b[2]))?;
    let triad = Matrix3::from_columns(&[u1, u2, u3]);
    let svd = triad.svd(true, true);
    if svd.singular_values.iter().any(|&s| (s - 1.0).abs() > 0.05) {
        return None;
    }
    let (u, v_t) = (svd.u?, svd.v_t?);
    let frame = u * v_t;
    let ft = frame.transpose();
    if !operations
        .iter()
        .all(|g| is_signed_permutation(&(ft * g * frame)))
    {
        return None;
    }
    Some(frame)
}

/// Generates an $O_h$-invariant Lebedev angular quadrature exact up to spherical harmonic degree
/// at least `degree` (up to degree 47), aligned with `frame`.
pub(super) fn octahedral_rule(
    degree: usize,
    frame: &Matrix3<f64>,
) -> Option<([Vec<f64>; 3], Vec<f64>)> {
    let table = match degree {
        0..=17 => LEBEDEV_17,
        18..=23 => LEBEDEV_23,
        24..=29 => LEBEDEV_29,
        30..=31 => LEBEDEV_31,
        32..=35 => LEBEDEV_35,
        36..=41 => LEBEDEV_41,
        42..=47 => LEBEDEV_47,
        _ => return None,
    };
    let mut directions = [Vec::new(), Vec::new(), Vec::new()];
    let mut weights = Vec::new();
    for &(seed, w) in table {
        for v in expand_seed(seed) {
            let rotated = frame * v;
            directions[0].push(rotated[0]);
            directions[1].push(rotated[1]);
            directions[2].push(rotated[2]);
            weights.push(w);
        }
    }
    Some((directions, weights))
}

#[cfg(test)]
mod tests {
    use super::{octahedral_frame, octahedral_rule};
    use crate::math::angular;
    use nalgebra::{Matrix3, Rotation3, Vector3};
    use std::f64::consts::PI;

    #[test]
    fn lebedev_tables_integrate_harmonics_and_stay_octahedral() {
        let signs = [-1.0, 1.0];
        let mut oh = Vec::with_capacity(48);
        for p in [
            [0, 1, 2],
            [0, 2, 1],
            [1, 0, 2],
            [1, 2, 0],
            [2, 0, 1],
            [2, 1, 0],
        ] {
            for &s0 in &signs {
                for &s1 in &signs {
                    for &s2 in &signs {
                        let mut m = Matrix3::zeros();
                        m[(0, p[0])] = s0;
                        m[(1, p[1])] = s1;
                        m[(2, p[2])] = s2;
                        oh.push(m);
                    }
                }
            }
        }
        let frame = octahedral_frame(&oh).expect("O_h frame");
        assert!((frame - Matrix3::identity()).norm() < 1e-14);

        let rot = Rotation3::from_euler_angles(0.37, -0.81, 1.19).into_inner();
        let rotated_oh: Vec<_> = oh.iter().map(|g| rot * g * rot.transpose()).collect();
        let rotated_frame = octahedral_frame(&rotated_oh).expect("rotated O_h frame");
        for g in &rotated_oh {
            let back = rotated_frame.transpose() * g * rotated_frame;
            assert!(super::is_signed_permutation(&back));
        }

        for (degree, expected_len) in [
            (17, 110),
            (23, 194),
            (29, 302),
            (31, 350),
            (35, 434),
            (41, 590),
            (47, 770),
        ] {
            let (dirs, weights) = octahedral_rule(degree, &frame).unwrap();
            assert_eq!(weights.len(), expected_len);
            assert!((weights.iter().sum::<f64>() - 4.0 * PI).abs() < 1e-13);
            let mut max_err = 0.0f64;
            for l in 0..=degree {
                for m in -(l as i32)..=(l as i32) {
                    let sum: f64 = (0..weights.len())
                        .map(|i| {
                            let pt = [dirs[0][i], dirs[1][i], dirs[2][i]];
                            weights[i] * angular::cartesian(l, m, pt)
                        })
                        .sum();
                    let exact = if l == 0 { (4.0 * PI).sqrt() } else { 0.0 };
                    max_err = max_err.max((sum - exact).abs());
                }
            }
            assert!(
                max_err < 1e-13,
                "degree {degree} spherical harmonic integration error {max_err:e}"
            );
            // Check rotated O_h invariance of an off-axis high-order function.
            let (rdirs, rw) = octahedral_rule(degree, &rotated_frame).unwrap();
            let f = |x: Vector3<f64>| (10.0 * (0.31 * x[0] + 0.52 * x[1] + 0.79 * x[2])).exp();
            let ref_val: f64 = (0..rw.len())
                .map(|i| rw[i] * f(Vector3::new(rdirs[0][i], rdirs[1][i], rdirs[2][i])))
                .sum();
            for g in &rotated_oh {
                let moved: f64 = (0..rw.len())
                    .map(|i| rw[i] * f(g * Vector3::new(rdirs[0][i], rdirs[1][i], rdirs[2][i])))
                    .sum();
                assert!((moved - ref_val).abs() < 1e-13 * ref_val.abs());
            }
        }
    }
}
