def compact_table(arrays: dict) -> dict:
    """Library arrays: the codec is exact, so the digest is the gate.
    Positional lists (names, sha256 of the float64 bytes, shape, max) keep the
    tracked JSON small; ``shape`` is ``n`` for a vector."""
    import numpy as np
    names, shas, shapes, maxima = [], [], [], []
    for name, array in arrays.items():
        a = np.asarray(array, dtype=float)
        d = fp(a, samples=0)
        names.append(name)
        shas.append(d["sha256"])
        shapes.append(d["shape"][0] if len(d["shape"]) == 1 else d["shape"])
        maxima.append(d.get("max"))
    return {"names": names, "sha256": shas, "shape": shapes, "max": maxima}


