def intruding_inputs(pp) -> dict:
    """What :func:`intruding_s_miss` reads, cropped at the first node past the
    sphere (the function masks ``0 < r <= r_cut``): the grid, the s pseudo
    waves and projectors, ``r_cut``; the miss itself."""
    import numpy as np
    from mandacaru.pseudopotentials.paw import intruding_s_miss
    channel = pp.channels.get(0)
    miss = intruding_s_miss(pp)
    if channel is None:
        return {"has_s": False, "miss": None}
    r = np.asarray(pp.r)
    last = int(np.searchsorted(r, channel.r_cut, side="right"))   # first node past the sphere
    stop = min(last + 1, r.size)
    return {"has_s": True, "miss": miss, "r_cut": float(channel.r_cut),
            "r": np.array(r[:stop]),
            "pseudo_waves": [np.array(np.asarray(w)[:stop]) for w in channel.pseudo_waves],
            "projectors": [np.array(np.asarray(w)[:stop]) for w in channel.projectors]}


class Recorder:
    """Patches the generator's module attributes (no src edit) to record the
    inputs and outputs of the functions it calls on the *current* attempt."""

    NAMES = ("assemble_paw_channel", "pseudize_density", "_hartree_energy",
             "_xc_energies", "j_resolved_spin_orbit", "_intruding_s_acceptance")

    def __init__(self, spec, mode="repair", keep=None):
        from mandacaru.pseudopotentials import dataset, paw, partial_waves
        self.paw, self.dataset, self.pw = paw, dataset, partial_waves
        self.names, self.only_l = spec if spec else ((), None)
        self.mode, self.keep = mode, keep
        self.attempts: list = []
        self.current = {}
        self.tried = None
        self.by_attempt = {}
        self.refused = {}           # attempt index -> acceptance inputs, when the acceptance refused it
        self.selected_index = None
        self.generate_calls = 0
        self.original = {n: getattr(paw, n) for n in self.NAMES}
        self.original["generate_paw"] = paw.generate_paw
        self.original_local = dataset._local_derivatives
        self.original_checks = {n: getattr(partial_waves, n) for n in (
            "ghost_errors", "scattering_errors", "unprojected_scattering_errors")}

    # -- install -------------------------------------------------------------
    def install(self):
        for name in self.NAMES:
            setattr(self.paw, name, self._wrap(name))
        self.dataset._local_derivatives = self._wrap_local()
        self.paw.generate_paw = self._wrap_generate()
        for name, fn in self.original_checks.items():
            setattr(self.pw, name, self._wrap_check(name, fn))

    def uninstall(self):
        for name in self.NAMES:
            setattr(self.paw, name, self.original[name])
        self.paw.generate_paw = self.original["generate_paw"]
        self.dataset._local_derivatives = self.original_local
        for name, fn in self.original_checks.items():
            setattr(self.pw, name, fn)

    # -- wrappers ------------------------------------------------------------
    def _wrap(self, name):
        original = self.original[name]

        def recorded(*args, **kwargs):
            result = original(*args, **kwargs)
            wanted = name in self.names
            if name == "_intruding_s_acceptance":
                # compact inputs of the acceptance (arrays inside the sphere),
                # no reference to the dataset.  ghost_free calls it right after
                # the candidate's generate_paw returned: the outcome belongs to
                # the last attempt, and a refusal keeps its inputs.
                prepared = intruding_inputs(args[0])
                self.current.setdefault(name, []).append((prepared, {}, result))
                if self.attempts:
                    self.attempts[-1]["intruding_s_miss"] = prepared["miss"]
                    self.attempts[-1]["acceptance"] = jsonable(result)
                    if result:
                        self.refused[self.attempts[-1]["index"]] = (prepared, {}, result)
                wanted = False
            if wanted and name == "assemble_paw_channel" and self.only_l is not None:
                wanted = int(args[1].l) in self.only_l
            if wanted:
                self.current.setdefault(name, []).append((args, kwargs, result))
            return result
        return recorded

    def _wrap_local(self):
        original = self.original_local

        def recorded(*args, **kwargs):
            result = original(*args, **kwargs)
            if "_local_derivatives" in self.names:
                self.current.setdefault("_local_derivatives", []).append(
                    (args, kwargs, result))
            return result
        return recorded

    def _wrap_check(self, name, original):
        def recorded(*args, **kwargs):
            try:
                result = original(*args, **kwargs)
            except Exception as error:      # DiagnosticError etc.
                if self.attempts:
                    self.attempts[-1].setdefault("checks", {})[name] = {
                        "raised": f"{type(error).__name__}: {error}"}
                raise
            if self.attempts:
                self.attempts[-1].setdefault("checks", {})[name] = jsonable(result)
            return result
        return recorded

    def _prune(self, index):
        """Retain the recorded calls of the attempt that will be selected and
        nothing else (every attempt would hold tens of MB of inputs; the Ce
        search has 33 attempts).  A hint ``keep`` (the selected index of the
        frozen run) wins; ``repair`` returns its last attempt, so the previous
        ones are dropped when the next starts; ``flag`` without a hint keeps
        all of them."""
        if self.keep is not None:
            for k in [k for k in self.by_attempt if k != self.keep]:
                self.by_attempt.pop(k)
        elif self.mode == "repair":
            for k in [k for k in self.by_attempt if k != index]:
                self.by_attempt.pop(k)

    def _wrap_generate(self):
        original = self.original["generate_paw"]

        def recorded(symbol, **kwargs):
            if kwargs.get("ghosts", "repair") != "keep":
                return original(symbol, **kwargs)       # the public entry
            frame = sys._getframe(1)
            label, remedy = None, None
            if frame.f_code.co_name == "ghost_free":
                label = frame.f_locals.get("label")
                remedy = frame.f_locals.get("remedy")
                tried = frame.f_locals.get("tried")
                if isinstance(tried, list):
                    self.tried = tried
            index = self.generate_calls
            self.generate_calls += 1
            self.current = {}
            record = {"index": index,
                      "label": label if label is not None else
                      ("first construction" if index == 0 else None),
                      "remedy": _remedy_json(remedy)}
            self.attempts.append(record)
            started = time.time()
            try:
                result = original(symbol, **kwargs)
            except Exception as error:
                record["raised"] = f"{type(error).__name__}: {error}"
                record["seconds"] = time.time() - started
                raise
            record["seconds"] = time.time() - started
            record["generated"] = {
                "r_cut": {str(l): float(c.r_cut) for l, c in result.channels.items()},
                "r_cut_local": float(result.r_cut_local),
                "local_shift": float(result.local_shift),
                "n_bessel": {str(l): len(c.wavevectors[0]) for l, c in result.channels.items()},
                "norm_deficit": result.norm_deficit,
                "one_center_energy": float(result.one_center_energy),
                "compensation_charge": float(result.compensation_charge)}
            record["_ref"] = weakref.ref(result)
            self.by_attempt[index] = self.current
            self._prune(index)
            return result
        return recorded


def select_attempt(rec: Recorder, pp):
    """Index and label of the attempt whose dataset ``ghost_free`` returned:
    by identity (``repair`` returns the last attempt, ``flag`` the least
    defective one); ``generate_upaw`` copies the dataset, so there the last
    attempt is taken and said so."""
    for record in rec.attempts:
        ref = record.get("_ref")
        if ref is not None and ref() is pp:
            return record["index"], record["label"], "identity"
    last = rec.attempts[-1]
    return last["index"], last["label"], "last attempt (dataset copied by the caller)"


