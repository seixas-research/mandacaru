#!/usr/bin/env python
"""Freeze the LIVE Python PAW generator before it is ported to Rust (plan A0).

What this writes (all under ``test/migration/reference/paw_generate/``):

* ``stamps.json``       sha256 of the generator sources, the extension, the
                        library files used, package versions, git HEAD.
* ``gen_<set>_<El>.json/.npz``   one generated dataset: scalars, the
                        ``ghost_free`` attempt table, per-array fingerprints,
                        and the recorded inputs/outputs of the functions the
                        generator called on the selected attempt.
* ``lib_<set>_<El>.json``        the shipped library file read through the
                        Python codec (``from_payload`` arrays: the A1 oracle)
                        plus the dataset-level function cases on it.
* ``misc.json``         ``_table`` edge cases and ``_local_derivatives`` cases.
* ``intruding_scan_<set>.json``  ``intruding_s_miss`` of every shipped file and
                        the ones the repair search's acceptance (>= 1.0) refuses.
* ``intruding_s.json/_inputs.npz``  the acceptance on real (shipped file with
                        miss >= 1) and synthetic inputs, boundaries included.
* ``census_<set>.json``  generation parameters of every shipped file (which
                        ``ghost_free`` attempt each one was built with).
* ``runs.json``         wall time and peak total memory of every child.
* ``pb_parquet.json``   the D-16 inspection of ``pbe-fr/Pb.parquet``.

The ``.npz`` files are git-ignored (``.gitignore``: ``*.npz``).  They are
regenerated by this script while the Python generator exists::

    python test/migration/freeze_paw_generation.py run --all
    python test/migration/freeze_paw_generation.py verify

Every number that decides pass or fail is in the tracked JSON.  Each radial
array carries ``sha256`` (of its float64 bytes), ``shape``, ``max`` and 16
sampled values; a ``blob`` key names the (decimated, ``stride``) array in the
npz when a pointwise comparison is wanted.  ``stride`` keeps the points
``a[stride-1::stride]`` (the rule of ``io._table``).

One element per child process, total memory under 1 GB: the parent only
spawns ``--child`` runs (guarded by ``memguard.py``) and merges their JSON.
"""
