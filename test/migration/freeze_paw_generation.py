def leaves_with_digests(value, prefix=""):
    """Numbers, and the strings that name a digest (``sha256``/``blob``)."""
    if isinstance(value, dict):
        for k, v in value.items():
            if k in ("sha256", "blob") and isinstance(v, str):
                yield f"{prefix}.{k}", v
            else:
                yield from leaves_with_digests(v, f"{prefix}.{k}" if prefix else str(k))
    elif isinstance(value, (list, tuple)):
        for i, v in enumerate(value):
            yield from leaves_with_digests(v, f"{prefix}[{i}]")
    elif isinstance(value, (int, float)) and not isinstance(value, bool):
        yield prefix, float(value)


def compare_functions(frozen, again) -> tuple:
    """(worst relative difference of the numbers, number of digest mismatches,
    missing keys) between the frozen JSON branch and a recomputation."""
    old = dict(leaves_with_digests(frozen))
    new = dict(leaves_with_digests(jsonable(again)))
    worst, digests, missing = 0.0, 0, 0
    for key, value in old.items():
        if key not in new:
            missing += 1
            continue
        if isinstance(value, str):
            digests += int(new[key] != value)
            continue
        diff = abs(new[key] - value) / max(abs(value), 1e-300) if value else abs(new[key])
        worst = max(worst, diff)
    return worst, digests, missing


