def dataset_arrays(pp) -> dict:
    """Every float array of a PAWDataset in the order of ``to_payload``."""
    import numpy as np
    out = {"r": pp.r, "v_local": pp.v_local,
           "v_local_screened": pp.v_local_screened,
           "valence_density": pp.valence_density,
           "core_density": pp.core_density,
           "smooth_core_density": pp.smooth_core_density}
    for l in sorted(pp.channels):
        ch = pp.channels[l]
        for i in range(len(ch.pseudo_waves)):
            out[f"ae_wave_l{l}_{i}"] = ch.ae_waves[i]
            out[f"pseudo_wave_l{l}_{i}"] = ch.pseudo_waves[i]
            out[f"projector_l{l}_{i}"] = ch.projectors[i]
            out[f"raw_projector_l{l}_{i}"] = ch.raw_projectors[i]
            out[f"wavevectors_l{l}_{i}"] = ch.wavevectors[i]
            out[f"wave_coefficients_l{l}_{i}"] = ch.wave_coefficients[i]
        for name in ("coupling", "coupling_screened", "overlap_correction",
                     "norm_correction", "kinetic_difference",
                     "potential_difference", "vanderbilt"):
            value = getattr(ch, name)
            out[f"{name}_l{l}"] = np.asarray(value, dtype=float)
        out[f"reference_energies_l{l}"] = np.asarray(ch.reference_energies, float)
        out[f"occupations_l{l}"] = np.asarray(ch.occupations, float)
        out[f"residual_kinetic_l{l}"] = np.asarray(ch.residual_kinetic, float)
    for l in sorted(pp.spin_orbit or {}):
        so = pp.spin_orbit[l]
        for k, p in enumerate(so["projectors"]):
            out[f"so_projector_l{l}_{k}"] = p
        for name in ("average", "average_screened", "coupling",
                     "coupling_screened", "overlap_average",
                     "overlap_coupling", "level_errors"):
            out[f"so_{name}_l{l}"] = np.asarray(so[name], dtype=float)
        out[f"so_reference_energies_l{l}"] = np.asarray(
            so["reference_energies"], dtype=float)
    return out


