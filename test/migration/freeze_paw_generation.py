def flatten_channel(ch) -> dict:
    import numpy as np
    flat = {}
    for i, p in enumerate(ch.projectors):
        flat[f"projector_{i}"] = p
    for i, p in enumerate(ch.raw_projectors):
        flat[f"raw_projector_{i}"] = p
    for i, p in enumerate(ch.pseudo_waves):
        flat[f"pseudo_wave_{i}"] = p
    for name in ("overlap_correction", "norm_correction", "kinetic_difference",
                 "potential_difference", "coupling_screened", "vanderbilt"):
        flat[name] = np.asarray(getattr(ch, name), dtype=float)
    for name in ("duality_error", "overlap_minimum", "asymmetry",
                 "consistency_error", "norm_error", "eigenvalue", "r_cut",
                 "occupation", "n"):
        flat[name] = np.asarray(float(getattr(ch, name)))
    flat["reference_energies"] = np.asarray(ch.reference_energies, float)
    return flat


def flatten_spin_orbit(spin_orbit) -> dict:
    import numpy as np
    flat = {}
    for l, e in spin_orbit.items():
        for k, p in enumerate(e["projectors"]):
            flat[f"l{l}.projector_{k}"] = p
        for name in ("average", "average_screened", "coupling",
                     "coupling_screened", "overlap_average",
                     "overlap_coupling", "level_errors"):
            flat[f"l{l}.{name}"] = np.asarray(e[name], dtype=float)
        flat[f"l{l}.reference_energies"] = np.asarray(e["reference_energies"], float)
    return flat


def store_outputs(flat: dict, blobs: Blobs) -> dict:
    import numpy as np
    stored = {}
    for name, value in flat.items():
        a = np.asarray(value, dtype=float)
        if a.size <= 64:                    # whole, exact (repr round-trips a float64)
            stored[name] = {"shape": list(a.shape), "values": a.reshape(-1).tolist()}
        else:
            stored[name] = entry(a, blobs, "o", OUT_POINTS, samples=3)
    return stored


def blob_of(spec: dict) -> str:
    """npz key of a stored output: named, or (after compaction) ``o_`` plus the
    first 20 hex digits of the sha256 of the full float64 array."""
    return spec.get("blob") or "o_" + spec["sha256"][:20]


def compare_outputs(flat: dict, stored: dict, npz) -> dict:
    """Per output: exact flag, max |difference| and it relative to the max."""
    import numpy as np
    report = {}
    for name, ref in stored.items():
        if name not in flat:
            report[name] = {"missing": True}
            continue
        a = np.asarray(flat[name], dtype=float)
        if "values" in ref:
            b = np.asarray(ref["values"], dtype=float).reshape(ref["shape"])
            scale = max(float(np.max(np.abs(b))) if b.size else 0.0, 1e-300)
            diff = float(np.max(np.abs(a - b))) if b.size else 0.0
            exact = bool(a.shape == b.shape and np.array_equal(a, b))
        else:
            exact = fp(a)["sha256"] == ref["sha256"]
            if exact:
                diff, scale = 0.0, ref.get("scale", ref.get("abs_max", abs(ref.get("max", 1.0))))
            else:
                b = npz[blob_of(ref)]
                n = int(np.prod(ref["shape"]))
                s = ref.get("stride") or int(math.ceil(n / OUT_POINTS))
                diff = float(np.max(np.abs(np.ascontiguousarray(a)[s - 1::s] - b)))
                scale = ref.get("scale", ref.get("abs_max", abs(ref.get("max", 1.0))))
        report[name] = {"exact": bool(exact), "max_abs": diff,
                        "max_rel_to_max": diff / scale if scale else diff}
    return report


def load_array(npz, spec):
    import numpy as np
    if "values" in spec:
        return np.asarray(spec["values"], dtype=float).reshape(spec["shape"])
    return np.asarray(npz[spec["blob"]], dtype=float)


def replay(case: dict, inputs_npz):
    """Re-run the recorded function on its stored inputs; returns the flat
    outputs.  ``inputs_npz`` is the loaded input archive."""
    from mandacaru.pseudopotentials import paw
    from mandacaru.pseudopotentials import dataset as ds
    from mandacaru.pseudopotentials.partial_waves import PseudoWaves
    inp = case["inputs"] if "inputs" in case else {}
    fn = case["function"]
    A = lambda spec: load_array(inputs_npz, spec)          # noqa: E731
    if fn == "assemble_paw_channel":
        p = inp["pw"]
        pw = PseudoWaves(
            l=p["l"], r_cut=p["r_cut"], energies=list(p["energies"]),
            waves=[A(s) for s in p["waves"]],
            wavevectors=[A(s) for s in p["wavevectors"]],
            coefficients=[A(s) for s in p["coefficients"]],
            residual_kinetic=list(p["residual_kinetic"]),
            norms=A(p["norms"]), achieved=A(p["achieved"]), q_cut=p["q_cut"],
            targets=None if p["targets"] is None else A(p["targets"]))
        ch = paw.assemble_paw_channel(
            A(inp["r"]), pw, A(inp["v_ae"]), A(inp["v_loc"]), n=inp["n"],
            occupations=inp["occupations"], strict=inp["strict"],
            r_local=inp["r_local"])
        return flatten_channel(ch)
    if fn == "pseudize_density":
        return {"smooth": paw.pseudize_density(A(inp["r"]), A(inp["density"]), inp["r_cut"])}
    if fn == "_local_derivatives":
        return {"derivatives": ds._local_derivatives(
            A(inp["r"]), A(inp["values"]), inp["r0"], order=inp["order"],
            window=inp["window"], degree=inp["degree"])}
    if fn == "_hartree_energy":
        return {"energy": paw._hartree_energy(A(inp["r"]), A(inp["rho"]))}
    if fn == "_xc_energies":
        from mandacaru.basis.xc import xc_potential
        r, rho = A(inp["r"]), A(inp["rho"])
        e = paw._xc_energies(r, rho, inp["xc"], inp["relativistic"])
        e_xc, v_xc = xc_potential(r, rho, inp["xc"], relativistic=inp["relativistic"])
        return {"E_xc": e[0], "int_rho_v_xc": e[1], "e_xc_density": e_xc, "v_xc": v_xc}
    if fn == "j_resolved_spin_orbit":
        a = inp["atom"]
        atom = SimpleNamespace(
            r=A(a["r"]), v_effective=A(a["v_effective"]),
            eigenvalues={tuple(int(x) for x in k.split(",")): v
                         for k, v in a["eigenvalues"].items()},
            eigenvalues_j={tuple(int(x) for x in k.split(",")): v
                           for k, v in a["eigenvalues_j"].items()})
        out = paw.j_resolved_spin_orbit(
            inp["symbol"], atom,
            {tuple(int(x) for x in k.split(",")): v
             for k, v in inp["valence_config"].items()},
            {int(l): c for l, c in inp["cutoffs"].items()},
            inp["rc_factor"], inp["energy_offset"], A(inp["v_loc"]),
            inp["r_local"], inp["q_cut"], inp["n_bessel"],
            inp["hartree_screening"], extra_l=inp["extra_l"],
            extra_energy=inp["extra_energy"],
            second_references={int(l): e for l, e in inp["second_references"].items()})
        return flatten_spin_orbit(out)
    if fn == "intruding_s_miss":
        pp = SimpleNamespace(symbol="replay", channels={}, r=None)
        if inp["has_s"]:
            pp.r = A(inp["r"])
            pp.channels = {0: SimpleNamespace(
                r_cut=inp["r_cut"], pseudo_waves=[A(w) for w in inp["pseudo_waves"]],
                projectors=[A(w) for w in inp["projectors"]])}
        return intruding_flat(paw.intruding_s_miss(pp), paw._intruding_s_acceptance(pp))
    raise ValueError(fn)


def perturb(case: dict, inputs_npz, seed: int):
    """A copy of the input archive with the principal arrays of the case
    moved by one ulp (random direction, fixed seed)."""
    import numpy as np
    rng = np.random.default_rng(seed)
    inp = case.get("inputs", {})
    fn = case["function"]
    names = {"assemble_paw_channel": ("v_ae", "v_loc"),
             "pseudize_density": ("density",), "_local_derivatives": ("values",),
             "_hartree_energy": ("rho",), "_xc_energies": ("rho",),
             "j_resolved_spin_orbit": ("v_loc",), "intruding_s_miss": ()}[fn]
    patched = Overlay(inputs_npz)
    specs = [inp[n] for n in names]
    if fn == "j_resolved_spin_orbit":
        specs.append(inp["atom"]["v_effective"])
    if fn == "intruding_s_miss" and inp.get("has_s"):
        specs += list(inp["pseudo_waves"]) + list(inp["projectors"])
    for spec in specs:
        if "blob" not in spec:
            continue
        a = np.array(inputs_npz[spec["blob"]], dtype=float)
        sign = rng.choice([-np.inf, np.inf], size=a.shape)
        patched[spec["blob"]] = np.nextafter(a, sign)
    return patched


class Overlay(dict):
    """Modified arrays over a lazily read archive (an npz is not loaded whole)."""

    def __init__(self, base):
        super().__init__()
        self.base = base

    def __missing__(self, key):
        return self.base[key]


