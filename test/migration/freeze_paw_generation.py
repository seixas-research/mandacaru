# The dataset as an input: the payload of the codec (stride 4, 10 digits: the
# object every production path reads), stored as plain arrays.
# --------------------------------------------------------------------------- #
def store_dataset(payload: dict, store: dict) -> dict:
    """Write the payload into ``store`` (an npz dict): the JSON of everything
    that is not a radial table (``ds_payload_json``, uint8), every radial
    table and every spin-orbit projector as ``ds_t_<name>`` /
    ``ds_so_<l>_<k>``.  Returns the summary kept in the tracked JSON."""
    import numpy as np
    meta = {k: v for k, v in payload.items() if k != "radial_tables"}
    spin = {}
    for l, entry_l in (payload.get("spin_orbit") or {}).items():
        spin[l] = dict(entry_l)
        for k, table in enumerate(entry_l["projectors"]):
            store[f"ds_so_{l}_{k}"] = np.asarray(table, dtype="<f8")
        spin[l]["projectors"] = len(entry_l["projectors"])
    meta["spin_orbit"] = spin
    text = json.dumps(meta, sort_keys=True).encode()
    store["ds_payload_json"] = np.frombuffer(text, dtype=np.uint8).copy()
    for name, values in payload["radial_tables"].items():
        store[f"ds_t_{name}"] = np.asarray(values, dtype="<f8")
    rows = sorted({int(np.asarray(v).size) for v in payload["radial_tables"].values()})
    return {"stride": 4, "payload_sha256": sha(text), "tables": len(payload["radial_tables"]),
            "rows": rows, "source": "paw.to_payload(pp, 4): _table, 10 significant digits"}


def rebuild_dataset(store):
    """The :class:`PAWDataset` of :func:`store_dataset` (``paw.from_payload``)."""
    import numpy as np
    from mandacaru.pseudopotentials import paw
    meta = json.loads(bytes(np.asarray(store["ds_payload_json"], dtype=np.uint8)).decode())
    for l, entry_l in (meta.get("spin_orbit") or {}).items():
        entry_l["projectors"] = [np.asarray(store[f"ds_so_{l}_{k}"], dtype=float)
                                 for k in range(entry_l["projectors"])]
    meta["radial_tables"] = {key[5:]: np.asarray(store[key], dtype=float)
                             for key in store.keys() if key.startswith("ds_t_")}
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        return paw.from_payload(meta)


