def _miss_of(prepared, factor=1.0):
    """The miss and the acceptance of ``prepared`` with the projectors scaled."""
    from mandacaru.pseudopotentials import paw
    pp = SimpleNamespace(symbol="synthetic", channels={}, r=prepared.get("r"))
    if prepared["has_s"]:
        pp.channels = {0: SimpleNamespace(
            r_cut=prepared["r_cut"], pseudo_waves=prepared["pseudo_waves"],
            projectors=[p * factor for p in prepared["projectors"]])}
    return paw.intruding_s_miss(pp), paw._intruding_s_acceptance(pp)


def _bisect_scale(prepared, target, lo, hi):
    """Projector scale whose miss is ``target`` on the rising branch."""
    for _ in range(300):
        mid = 0.5 * (lo + hi)
        if _miss_of(prepared, mid)[0] < target:
            lo = mid
        else:
            hi = mid
    return 0.5 * (lo + hi)


