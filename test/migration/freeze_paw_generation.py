def compare_with_library(pp, set_name, symbol, payload, arrays) -> dict:
    """The generated stride-4 tables against the shipped file (the end-to-end
    comparison of plan 3.4, step 2; informational, not a gate)."""
    import numpy as np
    if set_name == "upaw":
        return {"library": None}
    path = LIBRARY / set_name / f"{symbol}.parquet"
    if not path.exists():
        return {"library": None}
    from mandacaru.pseudopotentials.io import load_pseudopotential
    lib = load_pseudopotential(path)
    out = {"library": str(path.relative_to(LIBRARY.parent)), "sha256": file_sha(path)}
    tables = payload["radial_tables"]
    lib_arrays = dataset_arrays(lib)
    names = {"r": "r", "v_local": "v_local", "v_local_screened": "v_local_screened",
             "valence_density": "valence_density", "core_density": "core_density",
             "smooth_core_density": "smooth_core_density"}
    worst = (0.0, None)
    shape_mismatch = []
    for name in lib_arrays:
        if name.startswith(("ae_wave", "pseudo_wave", "projector", "raw_projector", "so_projector")) or name in names:
            key = name
            if name.startswith("so_projector"):
                continue
            new = np.asarray(tables.get(key, []), dtype=float)
            old = np.asarray(lib_arrays[name], dtype=float)
            if new.shape != old.shape or new.size == 0:
                shape_mismatch.append(name)
                continue
            scale = float(np.max(np.abs(old))) or 1.0
            rel = float(np.max(np.abs(new - old))) / scale
            if rel > worst[0]:
                worst = (rel, name)
    out["tables_max_rel_to_max"] = worst[0]
    out["tables_worst"] = worst[1]
    out["table_shape_mismatch"] = shape_mismatch[:6]
    scal = {}
    for k in ("one_center_energy", "compensation_charge", "hartree_screening",
              "r_cut_local", "local_shift", "compensation_radius"):
        scal[k] = float(getattr(pp, k)) - float(getattr(lib, k))
    for l in pp.channels:
        if l in lib.channels:
            for name in ("coupling_screened", "overlap_correction", "kinetic_difference"):
                a = np.asarray(getattr(pp.channels[l], name))
                b = np.asarray(getattr(lib.channels[l], name))
                if a.shape == b.shape:
                    scal[f"{name}_l{l}"] = float(np.max(np.abs(a - b)))
    out["scalars_abs_diff"] = scal
    so_new, so_old = pp.spin_orbit or {}, lib.spin_orbit or {}
    so = {}
    for l in so_new:
        if l in so_old:
            for name in ("coupling_screened", "average_screened", "overlap_coupling"):
                so[f"{name}_l{l}"] = float(np.max(np.abs(
                    np.asarray(so_new[l][name]) - np.asarray(so_old[l][name]))))
    out["spin_orbit_abs_diff"] = so
    out["matches_library_cutoffs"] = all(
        abs(pp.channels[l].r_cut - lib.channels[l].r_cut) < 1e-12 for l in pp.channels if l in lib.channels)
    return out


