def git_head() -> dict:
    def run(*args):
        return subprocess.run(["git", *args], cwd=ROOT, capture_output=True,
                              text=True).stdout.strip()
    return {"HEAD": run("rev-parse", "HEAD"),
            "dirty_files": [line for line in run("status", "--short").splitlines()
                            if "paw_generate" not in line][:40]}


_STAMP = []


def stamp_id() -> str:
    """16 hex digits identifying what every number depends on: sha256 of
    paw.py, partial_waves.py, dataset.py, io.py, the extension and the
    package versions (``stamps.json`` lists the components in full)."""
    if not _STAMP:
        parts = [file_sha(PSEUDO / name) for name in (
            "paw.py", "partial_waves.py", "dataset.py", "io.py")]
        parts += [file_sha(p) for p in sorted(SRC.glob("_native.cpython-314-darwin.so"))]
        parts += [json.dumps(versions(), sort_keys=True)]
        _STAMP.append(sha("|".join(parts).encode())[:16])
    return _STAMP[0]


def write_json(path, document):
    if isinstance(document, dict) and "stamp" not in document:
        document = {"stamp": stamp_id(), **document}
    text = json.dumps(jsonable(document), separators=(",", ":"), sort_keys=False)
    Path(path).write_text(text + "\n")


