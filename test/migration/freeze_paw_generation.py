def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def file_sha(path) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def jsonable(value):
    import numpy as np
    if isinstance(value, dict):
        return {(",".join(str(x) for x in k) if isinstance(k, tuple) else str(k)):
                jsonable(v) for k, v in value.items()}
    if isinstance(value, (list, tuple)):
        return [jsonable(v) for v in value]
    if isinstance(value, np.ndarray):
        return jsonable(value.tolist())
    if isinstance(value, (np.floating, float)):
        value = float(value)
        return value if math.isfinite(value) else repr(value)
    if isinstance(value, (np.integer,)):
        return int(value)
    if isinstance(value, (np.bool_,)):
        return bool(value)
    return value


def sample_index(n: int, peak: int, k: int = 16) -> list:
    """``k`` deterministic indices: both ends, the peak, then fractions.
    The JSON stores ``peak`` and the values ``val`` at ``sample_index(n,
    peak, len(val))`` (sorted, duplicates removed, ``n`` from ``shape``)."""
    picks = [0, n - 1, peak]
    for f in (.5, .25, .75, .1, .9, .35, .65, .2, .8, .05, .95, .4, .6):
        picks.append(int(f * (n - 1)))
    chosen = []
    for i in picks:
        if 0 <= i < n and i not in chosen:
            chosen.append(i)
        if len(chosen) == k:
            break
    return sorted(chosen)


def fp(array, samples=ARRAY_SAMPLES) -> dict:
    """sha256 of the float64 bytes, shape, max, abs max and ``samples``
    sampled values (``False`` or 0: none)."""
    import numpy as np
    a = np.ascontiguousarray(np.asarray(array, dtype="<f8"))
    flat = a.reshape(-1)
    out = {"sha256": sha(a.tobytes()), "shape": list(a.shape)}
    if flat.size == 0:
        return out
    peak = int(np.argmax(np.abs(flat)))
    out["max"] = float(flat.max())
    if abs(flat[peak]) != out["max"]:
        out["abs_max"] = float(abs(flat[peak]))
    if flat.size <= 8:
        out["values"] = [float(x) for x in flat]
    elif samples:
        index = sample_index(flat.size, peak, int(samples))
        out["peak"] = peak                    # idx = sample_index(n, peak, k)
        out["val"] = [float(f"{flat[i]:.15g}") for i in index]    # 15 digits
    return out


class Blobs:
    """Arrays kept in the npz, deduplicated by content."""

    def __init__(self):
        self.arrays: dict = {}

    def put(self, array, prefix: str, points: int | None = None):
        import numpy as np
        a = np.ascontiguousarray(np.asarray(array, dtype="<f8"))
        stride = 1
        if points is not None and a.ndim == 1 and a.size > points:
            stride = int(math.ceil(a.size / points))
            a = np.ascontiguousarray(a[stride - 1::stride])
        key = f"{prefix}_{sha(a.tobytes())[:20]}"
        self.arrays[key] = a
        return key, stride

    def save(self, path):
        import numpy as np
        np.savez_compressed(path, **self.arrays)


def entry(array, blobs: Blobs | None = None, prefix: str = "o",
          points: int | None = OUT_POINTS, samples: int = ARRAY_SAMPLES) -> dict:
    """Fingerprint of ``array`` and, when ``blobs`` is given, its npz copy."""
    import numpy as np
    a = np.asarray(array, dtype=float)
    info = fp(a, samples)
    if blobs is not None and a.size > 8:
        key, stride = blobs.put(a, prefix, points)
        info["blob"], info["stride"] = key, stride
    return info


