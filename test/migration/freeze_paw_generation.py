MEMORY_CAP_MB = 1000.0          # the owner's cap on TOTAL memory per process


def parse_time_l(text: str) -> dict:
    out = {}
    m = re.search(r"([\d.,]+)\s+real", text)
    if m:
        out["wall_seconds"] = float(m.group(1).replace(",", "."))
    m = re.search(r"(\d+)\s+maximum resident set size", text)
    if m:
        out["max_rss_mb"] = int(m.group(1)) / 1e6
    m = re.search(r"(\d+)\s+peak memory footprint", text)
    if m:
        out["peak_footprint_mb"] = int(m.group(1)) / 1e6
    return out


def child_id(stage, set_name=None, element=None) -> str:
    return ":".join(x for x in (stage, set_name, element) if x)


def update_runs(identifier: str, record: dict):
    if identifier.startswith(("verify", "libcheck", "xcheck")):
        return                                   # checks leave no record: they must not grow the folder
    import fcntl
    path = REF / "runs.json"
    SCRATCH.mkdir(parents=True, exist_ok=True)
    with open(SCRATCH / ".runs.lock", "w") as lock:      # two drivers may run at once
        fcntl.flock(lock, fcntl.LOCK_EX)
        runs = json.loads(path.read_text()) if path.exists() else {}
        runs[identifier] = record
        write_json(path, runs)


def run_child(stage, set_name=None, element=None, threads=1, timeout=7200,
              extra=()) -> int:
    """memguard, then ``/usr/bin/time -l python script --child ...``, with a
    monitor that kills the child if its RSS passes the cap."""
    REF.mkdir(parents=True, exist_ok=True)
    identifier = child_id(stage, set_name, element) + (f":t{threads}" if stage in ("gen", "rerun") else "")
    if not MEMGUARD.exists():
        raise SystemExit(f"memguard not found at {MEMGUARD}: no heavy child may start without it")
    if True:
        guard = subprocess.run([PYTHON, str(MEMGUARD), "--need-gb", "1", "--wait", "120"],
                               capture_output=True, text=True)
        if guard.returncode != 0:
            update_runs(identifier, {"status": "not started: memguard refused",
                                     "memguard": guard.stdout.strip()[-300:]})
            print(f"{identifier}: memguard refused: {guard.stdout.strip()[-200:]}")
            return 5
    cmd = ["/usr/bin/time", "-l", PYTHON, str(Path(__file__).resolve()), "--child", stage]
    if set_name:
        cmd += ["--set", set_name]
    if element:
        cmd += ["--element", element]
    cmd += list(extra)
    env = dict(os.environ, OMP_NUM_THREADS=str(threads), MANDACARU_PAW_PATH=str(LIBRARY),
               PYTHONUNBUFFERED="1")
    env.pop("MANDACARU_UPAW_PATH", None)
    started = time.time()
    process = subprocess.Popen(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True,
                               env=env, start_new_session=True)
    peak_rss = 0.0
    killed = None
    import signal
    while process.poll() is None:
        time.sleep(1.0)
        rss = subprocess.run(["ps", "-o", "rss=", "-g", str(process.pid)],
                             capture_output=True, text=True).stdout.split()
        total = sum(int(x) for x in rss if x.isdigit()) / 1024.0
        peak_rss = max(peak_rss, total)
        if total > MEMORY_CAP_MB:
            killed = f"killed at {total:.0f} MB RSS (cap {MEMORY_CAP_MB:.0f} MB)"
            os.killpg(process.pid, signal.SIGKILL)
            break
        if time.time() - started > timeout:
            killed = f"killed after {timeout} s"
            os.killpg(process.pid, signal.SIGKILL)
            break
    stdout, stderr = process.communicate()
    timing = parse_time_l(stderr)
    record = {"status": killed or ("ok" if process.returncode == 0 else f"exit {process.returncode}"),
              "threads": threads, "wall_s": round(timing.get("wall_seconds", 0.0), 1),
              "peak_footprint_mb": round(timing.get("peak_footprint_mb", 0.0)),
              "max_rss_mb": round(timing.get("max_rss_mb", 0.0)),
              "monitor_peak_rss_mb": round(peak_rss)}
    if "peak_footprint_mb" in record and record["peak_footprint_mb"] > MEMORY_CAP_MB and not killed:
        record["status"] += f" (EXCEEDS the {MEMORY_CAP_MB:.0f} MB cap)"
    if process.returncode != 0:
        record["stdout_tail"] = stdout.strip()[-400:]
        record["stderr_tail"] = stderr.strip()[-600:]
    update_runs(identifier, record)
    print(f"{identifier}: {record['status']}  wall {record['wall_s']:.1f}s  "
          f"footprint {record['peak_footprint_mb']:.0f} MB  rss {record['max_rss_mb']:.0f} MB")
    return process.returncode


def round_floats(node, digits=15):
    """Floats to ``digits`` significant digits (the function branches are
    compared at 1e-13 relative, and their digests carry the bitwise gate)."""
    if isinstance(node, float):
        return float(f"{node:.{digits}g}") if math.isfinite(node) else node
    if isinstance(node, dict):
        return {k: round_floats(v, digits) for k, v in node.items()}
    if isinstance(node, list):
        return [round_floats(v, digits) for v in node]
    return node


def slim_outputs(outputs: dict):
    """Function-case outputs kept as ``sha256``, ``shape``, ``scale`` (the
    largest magnitude: what a relative difference is divided by) and the npz
    ``blob``; the sampled values are in the npz."""
    for out in outputs.values():
        if isinstance(out, dict) and "blob" in out:
            if "scale" not in out:
                out["scale"] = out.get("abs_max", abs(out.get("max", 1.0)))
            for key in ("max", "abs_max", "peak", "val", "stride"):
                out.pop(key, None)


def slim_floor(case: dict):
    floor = case.get("floor")
    if not floor:
        return
    floor.pop("seconds", None)
    for group in ((floor.get("ulp_perturbation") or {}).get("groups") or {}).values():
        group.pop("max_abs", None)
        group.pop("worst", None)
        group.pop("tol_100x", None)         # 100 x max_rel_to_max


def slim_functions(node):
    """Dataset-level branches: drop the static recipe texts (they live once in
    ``manifest.json``) and the sampled values of the table entries."""
    if isinstance(node, dict):
        for key in ("recipe", "radii_recipe", "spline"):
            node.pop(key, None)
        if "sha256" in node and "shape" in node:
            for key in ("peak", "val", "stride", "abs_max"):
                node.pop(key, None)
        for value in node.values():
            slim_functions(value)
    elif isinstance(node, list):
        for value in node:
            slim_functions(value)


def compact_document(document: dict, npz_path=None) -> dict:
    """Idempotent size reduction, applied last (``run --all`` ends with it):

    * ``val`` keeps the first ``ARRAY_SAMPLES`` of the priority order of
      ``sample_index``;
    * per-attempt ``checks``/``generated`` stay only for the selected attempt
      (the ``tried`` strings carry every other outcome);
    * the npz key of ``arrays[name]`` is ``d_<name>`` and of ``atom[name]``
      ``a_<name>`` (renamed in the npz, ``blob`` dropped from the JSON); the
      decimation ``stride`` of every entry is ``ceil(n / GEN_POINTS)``
      (arrays, atom) or ``ceil(n / OUT_POINTS)`` (function outputs) with
      ``n`` from ``shape``, and is dropped;
    * warnings cut to 140 characters, the repeated note and empty detail of
      ``floor_rerun`` removed."""
    def shrink(node):
        if isinstance(node, dict):
            if "val" in node and "peak" in node and "shape" in node:
                n = 1
                for extent in node["shape"]:
                    n *= extent
                old = sample_index(n, node["peak"], len(node["val"]))
                keep = sample_index(n, node["peak"], min(ARRAY_SAMPLES, len(node["val"])))
                where = dict(zip(old, node["val"]))
                node["val"] = [where[i] for i in keep]
            for value in node.values():
                shrink(value)
        elif isinstance(node, list):
            for value in node:
                shrink(value)
    shrink(document)
    ghost = document.get("ghost_free")
    if ghost and ghost.get("attempts"):
        keep_index = ghost.get("selected_index")
        for record in ghost["attempts"]:
            if record.get("index") != keep_index:
                record.pop("generated", None)
                record.pop("checks", None)
            if isinstance(record.get("seconds"), float):
                record["seconds"] = round(record["seconds"], 1)
    case = (document.get("function_cases") or {}).get("intruding_s_miss.0")
    if ghost and ghost.get("attempts") and case:
        for record in ghost["attempts"]:       # the selected attempt, when the table lacks its outcome
            if record.get("index") == ghost.get("selected_index") and "intruding_s_miss" not in record:
                miss = case["outputs"]["miss"]["values"][0]
                record["intruding_s_miss"] = None if miss < 0 else miss
                record["acceptance"] = ({"s_miss": case["outputs"]["s_miss"]["values"][0]}
                                        if case["outputs"]["nonempty"]["values"][0] else {})
    for case in (document.get("function_cases") or {}).values():
        slim_outputs(case.get("outputs") or {})
        slim_floor(case)
    for table in (document.get("arrays"), document.get("atom", {}).get("orbitals")):
        for item in (table or {}).values():
            if isinstance(item, dict) and "values" in item:
                item.pop("sha256", None)    # whole array stored: sha256 of its float64 bytes is derived
    # the sampled values of the large tables are the d_/a_ arrays of the npz
    # (decimated to 2000 points: a superset); only sha256, shape and extrema stay
    for section in (document.get("arrays"), *[(document.get("atom") or {}).get(k)
                                              for k in ("r", "v_effective", "density")]):
        entries = section.values() if section is not None and "sha256" not in section else [section]
        for item in entries:
            if isinstance(item, dict) and "sha256" in item and "shape" in item:
                item.pop("val", None)
                item.pop("peak", None)
    if "dataset_functions" in document:
        slim_functions(document["dataset_functions"])
        document["dataset_functions"] = round_floats(document["dataset_functions"])
    if "warnings" in document:
        document["warnings"] = [w[:100] for w in document["warnings"]]
    document.pop("function_cases_note", None)
    for record in (ghost or {}).get("attempts", []):
        if record.get("index") != (ghost or {}).get("selected_index"):
            record.pop("remedy", None)      # the label states it
    for item in (document.get("atom") or {}).get("orbitals", {}).values():
        if isinstance(item, dict):
            item.pop("shape", None)
            item.pop("max", None)
    for case in (document.get("function_cases") or {}).values():
        for spec in _walk_specs(case.get("inputs", {})):
            if "blob" in spec:
                spec.pop("sha256", None)        # the blob name carries sha256[:20]
                spec.pop("shape", None)         # and the npz array its shape
        for key in ("e_xc_density", "v_xc"):
            out = (case.get("outputs") or {}).get(key)
            if isinstance(out, dict):
                out.pop("val", None)
                out.pop("peak", None)
    for rerun in (document.get("floor_rerun") or {}).values():
        for key in ("differing_arrays", "tables_worst", "scalars_worst", "arrays_compared"):
            if not rerun.get(key):
                rerun.pop(key, None)
    for case in (document.get("function_cases") or {}).values():
        for out in (case.get("outputs") or {}).values():
            if isinstance(out, dict):
                out.pop("stride", None)
    if npz_path is not None and Path(npz_path).exists():
        data = {k: v for k, v in np_load(npz_path).items()}
        changed = False
        renamed, old_keys = {}, set()
        for section, prefix in (("arrays", "d_"), ("atom", "a_")):
            for name, item in (document.get(section) or {}).items():
                if isinstance(item, dict) and "blob" in item:
                    renamed[f"{prefix}{name}"] = data[item["blob"]]
                    old_keys.add(item["blob"])      # identical arrays share one key
                    item.pop("blob")
                    changed = True
                if isinstance(item, dict):
                    item.pop("stride", None)
        for case in (document.get("function_cases") or {}).values():
            for item in (case.get("outputs") or {}).values():
                if isinstance(item, dict) and "blob" in item and "sha256" in item:
                    renamed["o_" + item["sha256"][:20]] = data[item["blob"]]
                    old_keys.add(item["blob"])
                    item.pop("blob")
                    changed = True
        if changed:
            for key in old_keys:
                data.pop(key, None)
            data.update(renamed)
            np_savez(npz_path, data)
    return document


def _walk_specs(node):
    if isinstance(node, dict):
        if "blob" in node or "values" in node:
            yield node
        for value in node.values():
            yield from _walk_specs(value)
    elif isinstance(node, list):
        for value in node:
            yield from _walk_specs(value)


def np_load(path):
    import numpy as np
    return np.load(path)


def np_savez(path, data):
    import numpy as np
    np.savez_compressed(path, **data)


