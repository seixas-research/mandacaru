def numeric_leaves(value, prefix=""):
    if isinstance(value, bool) or value is None or isinstance(value, str):
        return
    if isinstance(value, (int, float)):
        yield prefix, float(value)
    elif isinstance(value, dict):
        for k, v in value.items():
            yield from numeric_leaves(v, f"{prefix}.{k}" if prefix else str(k))
    elif isinstance(value, (list, tuple)):
        for i, v in enumerate(value):
            yield from numeric_leaves(v, f"{prefix}[{i}]")


def rerun_floor(set_name, symbol, pp, arrays, ghost) -> dict:
    """Compare this (second) generation with the frozen first one: every
    array against the scratch full-resolution archive, every scalar against
    the tracked JSON."""
    import numpy as np
    json_path, _d, _i = gen_files(set_name, symbol)
    frozen = json.loads(json_path.read_text())
    full = np.load(SCRATCH / f"full_{set_name}_{symbol}.npz")
    worst_table = (0.0, None)
    exact = 0
    differing = []
    max_rel = {"tables": 0.0, "small": 0.0}
    max_abs = {"tables": 0.0, "small": 0.0}
    for name, a in arrays.items():
        a = np.asarray(a, dtype=float)
        b = full[name]
        if a.shape != b.shape:
            differing.append((name, "shape"))
            continue
        d = float(np.max(np.abs(a - b))) if a.size else 0.0
        group = "tables" if a.size > 64 else "small"
        scale = float(np.max(np.abs(b))) or 1.0
        if d == 0.0:
            exact += 1
        else:
            differing.append((name, d))
        max_abs[group] = max(max_abs[group], d)
        max_rel[group] = max(max_rel[group], d / scale)
        if group == "tables" and d / scale > worst_table[0]:
            worst_table = (d / scale, name)
    scalar_diff = 0.0
    scalar_name = None
    new = dataset_scalars(pp)
    new_leaves = dict(numeric_leaves(jsonable(new)))
    for key, old in numeric_leaves(frozen["scalars"]):
        if key in new_leaves:
            diff = abs(new_leaves[key] - old)
            if diff > scalar_diff:
                scalar_diff, scalar_name = diff, key
    return {
        "threads": os.environ.get("OMP_NUM_THREADS"),
        "arrays_compared": len(arrays), "arrays_bit_identical": exact,
        "tables_max_abs": max_abs["tables"], "tables_max_rel_to_max": max_rel["tables"],
        "tables_worst": worst_table[1],
        "small_max_abs": max_abs["small"], "small_max_rel_to_max": max_rel["small"],
        "scalars_max_abs": scalar_diff, "scalars_worst": scalar_name,
        "differing_arrays": differing[:8],
        "same_selected_attempt": ghost["selected_index"] == frozen["ghost_free"]["selected_index"],
        "same_selected_label": ghost["selected_label"] == frozen["ghost_free"]["selected_label"]}


def group_of(name: str) -> str:
    base = name.split(".")[-1]
    if base.startswith(("projector", "raw_projector", "pseudo_wave", "smooth", "derivatives",
                        "e_xc_density", "v_xc")):
        return "tables"
    if base in ("duality_error", "asymmetry", "consistency_error", "norm_error"):
        return "diagnostics"
    if base in ("overlap_correction", "norm_correction", "kinetic_difference",
                "potential_difference", "coupling_screened", "vanderbilt",
                "average", "average_screened", "coupling", "overlap_average",
                "overlap_coupling"):
        return "matrices"
    return "scalars"


def flat_diff(a: dict, b: dict) -> dict:
    """Max |difference| per output group, absolute and relative to each
    output's own maximum (the quantity a port is judged on)."""
    import numpy as np
    groups: dict = {}
    for name, x in a.items():
        y = b[name]
        x, y = np.asarray(x, float), np.asarray(y, float)
        d = float(np.max(np.abs(x - y))) if x.size else 0.0
        scale = float(np.max(np.abs(x))) if x.size else 0.0
        rel = d / scale if scale > 0 else d
        g = groups.setdefault(group_of(name), {"max_abs": 0.0, "max_rel_to_max": 0.0, "worst": None})
        g["max_abs"] = max(g["max_abs"], d)
        if rel > g["max_rel_to_max"]:
            g["max_rel_to_max"], g["worst"] = rel, name
    return groups


def child_floors(args) -> int:
    """Replay every recorded function on its stored inputs in a fresh
    process: bitwise reproduction of the frozen outputs, then the 1-ulp
    sensitivity.  With ``--check`` nothing is written and a mismatch fails."""
    import numpy as np
    json_path, data_path, inputs_path = gen_files(args.set, args.element)
    if not inputs_path.exists() or not data_path.exists():
        print(f"MISSING {inputs_path.name} / {data_path.name}: regenerate with "
              f"`python {SCRIPT} run gen:{args.set}:{args.element}`")
        return 4
    doc = json.loads(json_path.read_text())
    inputs = np.load(inputs_path)
    data = np.load(data_path)
    bad = 0
    for name, case in doc["function_cases"].items():
        if "inputs" not in case:
            continue
        started = time.time()
        flat = replay(case, inputs)
        report = compare_outputs(flat, case["outputs"], data)
        exact = all(r.get("exact") for r in report.values())
        worst = max((r["max_rel_to_max"] for r in report.values() if "max_rel_to_max" in r), default=0.0)
        floor = {"reproduces_frozen_bitwise": exact,
                 "frozen_max_rel_to_max": worst,
                 "seconds": time.time() - started}
        if worst > 1e-13:
            bad += 1
        if not args.check:
            runs = []
            for seed in (1, 2, 3):
                moved = perturb(case, inputs, seed)
                runs.append(flat_diff(flat, replay(case, moved)))
            ulp = {}
            for g in ("tables", "matrices", "scalars", "diagnostics"):
                vals = [r[g] for r in runs if g in r]
                if vals:
                    best = max(vals, key=lambda v: v["max_rel_to_max"])
                    ulp[g] = {"max_abs": max(v["max_abs"] for v in vals),
                              "max_rel_to_max": best["max_rel_to_max"],
                              "worst": best["worst"],
                              "tol_100x": 100.0 * best["max_rel_to_max"]}
            floor["ulp_perturbation"] = {"seeds": 3, "groups": ulp}
            case["floor"] = floor
        print(f"{args.set} {args.element} {name}: bitwise={exact} frozen_rel={worst:.2e}")
    if "dataset_functions" in doc:
        started = time.time()
        pp4 = rebuild_dataset(inputs)
        worst, digests, missing = compare_functions(
            doc["dataset_functions"], library_functions(pp4, Blobs()))
        sha_ok = sha(bytes(inputs["ds_payload_json"])) == doc["dataset_input"]["payload_sha256"]
        if worst > 1e-13 or digests or missing or not sha_ok:
            bad += 1
        print(f"{args.set} {args.element} dataset_functions: max rel {worst:.2e} "
              f"digest mismatches {digests} missing {missing} input_sha_ok={sha_ok} "
              f"({time.time() - started:.1f}s)")
    if not args.check:
        write_json(json_path, doc)
    return 1 if bad else 0


