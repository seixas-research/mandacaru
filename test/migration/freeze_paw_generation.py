def record_inputs(rec: Recorder, pp, in_blobs: Blobs, out_blobs: Blobs) -> dict:
    """Serialize the recorded calls of the selected attempt."""
    import numpy as np
    cases: dict = {}

    def inp(array):
        # every input array lives in the npz (the tracked JSON stays small);
        # the blob name carries the first 20 hex digits of its sha256
        a = np.asarray(array, dtype=float)
        key, _ = in_blobs.put(a, "i", None)
        return {"blob": key, "sha256": fp(a, 0)["sha256"], "shape": list(a.shape)}

    cur = rec.last_inputs
    # assemble_paw_channel -------------------------------------------------
    for k, (args, kw, ch) in enumerate(cur.get("assemble_paw_channel", [])):
        r, pw, v_ae, v_loc = args[:4]
        n = kw.get("n", args[4] if len(args) > 4 else None)
        occupations = kw.get("occupations", args[5] if len(args) > 5 else ())
        strict = kw.get("strict", args[6] if len(args) > 6 else True)
        r_local = kw.get("r_local", args[7] if len(args) > 7 else 0.0)
        cond = float(np.linalg.cond(np.asarray(ch.vanderbilt, dtype=float)))
        case = {
            "function": "assemble_paw_channel",
            "inputs": {"r": inp(r), "v_ae": inp(v_ae), "v_loc": inp(v_loc),
                       "n": int(n), "occupations": [float(o) for o in occupations],
                       "strict": bool(strict), "r_local": float(r_local),
                       "pw": {"l": int(pw.l), "r_cut": float(pw.r_cut),
                              "energies": [float(e) for e in pw.energies],
                              "waves": [inp(w) for w in pw.waves],
                              "wavevectors": [inp(q) for q in pw.wavevectors],
                              "coefficients": [inp(c) for c in pw.coefficients],
                              "residual_kinetic": [float(e) for e in pw.residual_kinetic],
                              "norms": inp(pw.norms), "achieved": inp(pw.achieved),
                              "q_cut": float(pw.q_cut),
                              "targets": None if pw.targets is None else inp(pw.targets)}},
            "condition_number_vanderbilt": cond,
            "outputs": store_outputs(flatten_channel(ch), out_blobs)}
        cases[f"assemble_paw_channel.l{pw.l}.{k}"] = case
    # pseudize_density ------------------------------------------------------
    for k, (args, kw, out) in enumerate(cur.get("pseudize_density", [])):
        r, density, r_cut = args[:3]
        cases[f"pseudize_density.{k}"] = {
            "function": "pseudize_density",
            "inputs": {"r": inp(r), "density": inp(density), "r_cut": float(r_cut)},
            "outputs": store_outputs({"smooth": out}, out_blobs)}
    # local derivatives (the exact rules the Rust variant must reproduce) --
    for k, (args, kw, out) in enumerate(cur.get("_local_derivatives", [])):
        r, values, r0 = args[:3]
        cases[f"_local_derivatives.{k}"] = {
            "function": "_local_derivatives",
            "inputs": {"r": inp(r), "values": inp(values), "r0": float(r0),
                       "order": int(kw.get("order", args[3] if len(args) > 3 else 4)),
                       "window": int(kw.get("window", args[4] if len(args) > 4 else 25)),
                       "degree": int(kw.get("degree", args[5] if len(args) > 5 else 8))},
            "outputs": store_outputs({"derivatives": out}, out_blobs),
            "nearest_node": int(np.argmin(np.abs(np.asarray(r) - float(r0))))}
    # energies --------------------------------------------------------------
    for k, (args, kw, out) in enumerate(cur.get("_hartree_energy", [])):
        r, rho = args[:2]
        cases[f"hartree_energy.{k}"] = {
            "function": "_hartree_energy",
            "inputs": {"r": inp(r), "rho": inp(rho)},
            "outputs": store_outputs({"energy": out}, out_blobs)}
    for k, (args, kw, out) in enumerate(cur.get("_xc_energies", [])):
        r, rho = args[:2]
        xc = kw.get("xc", args[2] if len(args) > 2 else "lda")
        rel = kw.get("relativistic", args[3] if len(args) > 3 else False)
        from mandacaru.basis.xc import xc_potential
        e_xc, v_xc = xc_potential(r, rho, xc, relativistic=rel)
        cases[f"xc_energies.{k}"] = {
            "function": "_xc_energies",
            "inputs": {"r": inp(r), "rho": inp(rho), "xc": str(xc),
                       "relativistic": bool(rel)},
            "outputs": store_outputs(
                {"E_xc": out[0], "int_rho_v_xc": out[1],
                 "e_xc_density": e_xc, "v_xc": v_xc}, out_blobs)}
    # j_resolved_spin_orbit -------------------------------------------------
    for k, (args, kw, out) in enumerate(cur.get("j_resolved_spin_orbit", [])):
        names = ["symbol", "atom", "valence_config", "cutoffs", "rc_factor",
                 "energy_offset", "v_loc", "r_local", "q_cut", "n_bessel",
                 "hartree_screening"]
        bound = dict(zip(names, args))
        bound.update(kw)
        atom = bound["atom"]
        cases[f"j_resolved_spin_orbit.{k}"] = {
            "function": "j_resolved_spin_orbit",
            "inputs": {
                "symbol": bound["symbol"],
                "atom": {"r": inp(atom.r), "v_effective": inp(atom.v_effective),
                         "eigenvalues": {f"{n},{l}": float(e) for (n, l), e in atom.eigenvalues.items()},
                         "eigenvalues_j": {f"{n},{l},{kk}": float(e)
                                           for (n, l, kk), e in atom.eigenvalues_j.items()}},
                "valence_config": {f"{n},{l}": float(o)
                                   for (n, l), o in bound["valence_config"].items()},
                "cutoffs": {str(l): float(c) for l, c in bound["cutoffs"].items()},
                "rc_factor": float(bound["rc_factor"]),
                "energy_offset": float(bound["energy_offset"]),
                "v_loc": inp(bound["v_loc"]), "r_local": float(bound["r_local"]),
                "q_cut": float(bound["q_cut"]), "n_bessel": int(bound["n_bessel"]),
                "hartree_screening": float(bound["hartree_screening"]),
                "extra_l": int(bound.get("extra_l", 0)),
                "extra_energy": (None if bound.get("extra_energy") is None
                                 else float(bound["extra_energy"])),
                "second_references": {str(l): float(e) for l, e in
                                      (bound.get("second_references") or {}).items()}},
            "outputs": store_outputs(flatten_spin_orbit(out), out_blobs)}
    # intruding_s_miss and the acceptance: one case per attempt that was run
    # on the selected attempt (the search calls it once per candidate)
    for k, (prepared, _kw, out) in enumerate(cur.get("_intruding_s_acceptance", [])):
        cases[f"intruding_s_miss.{k}"] = intruding_case(prepared, out, inp, out_blobs)
    for index, (prepared, _kw, out) in sorted(rec.refused.items()):
        if index != rec.selected_index:     # a candidate the acceptance refused and the search left
            cases[f"intruding_s_miss.refused_attempt{index}"] = intruding_case(
                prepared, out, inp, out_blobs)
    return cases


def intruding_flat(miss, accept) -> dict:
    """The outputs of an intruding-1s case as flat arrays (-1 for no s channel)."""
    import numpy as np
    return {"miss": np.asarray([-1.0 if miss is None else float(miss)]),
            "nonempty": np.asarray([1.0 if accept else 0.0]),
            "s_miss": np.asarray([float(accept.get("s_miss", 0.0)) if accept else 0.0])}


def intruding_case(prepared, accept, inp, out_blobs) -> dict:
    """``prepared`` is :func:`intruding_inputs`; ``accept`` the result of
    ``_intruding_s_acceptance`` for it."""
    inputs = {"has_s": bool(prepared["has_s"])}
    if prepared["has_s"]:
        inputs.update({"r": inp(prepared["r"]), "r_cut": prepared["r_cut"],
                       "pseudo_waves": [inp(w) for w in prepared["pseudo_waves"]],
                       "projectors": [inp(w) for w in prepared["projectors"]]})
    return {"function": "intruding_s_miss", "inputs": inputs,
            "outputs": store_outputs(intruding_flat(prepared["miss"], accept), out_blobs),
            "tolerance": 1.0}




