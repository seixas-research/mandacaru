def check_library(set_name, symbol, fresh, pp) -> int:
    """Re-read the shipped file and recompute: the digests of every array
    must be identical and the function cases equal the frozen JSON."""
    frozen = json.loads((REF / f"lib_{set_name}_{symbol}.json").read_text())
    bad = []
    if frozen["file"]["sha256"] != fresh["file"]["sha256"]:
        bad.append("file sha256 changed (the library file is not the frozen one)")
    if frozen["arrays"]["sha256"] != fresh["arrays"]["sha256"]:
        bad.append("array digests differ")
    worst = 0.0
    if "functions" in frozen:
        again = jsonable(library_functions(pp, Blobs()))
        old = dict(numeric_leaves(frozen["functions"]))
        new = dict(numeric_leaves(again))
        for key, value in old.items():
            if key not in new:
                bad.append(f"missing {key}")
                continue
            diff = abs(new[key] - value) / max(abs(value), 1e-300) if value else abs(new[key])
            worst = max(worst, diff)
        if worst > 1e-13:
            bad.append(f"function cases differ by {worst:.2e}")
    print(f"{set_name} {symbol}: " + ("OK" if not bad else "; ".join(bad))
          + f"  functions max rel {worst:.1e}")
    return 1 if bad else 0


def library_functions(pp, blobs: Blobs) -> dict:
    """The dataset-level functions on a shipped dataset: inputs are the file
    (named by its sha256 in the parent document) and the recipes below."""
    import numpy as np
    from mandacaru.pseudopotentials import paw
    from mandacaru.pseudopotentials.multipoles import multipole_range
    out: dict = {}
    # log_derivative_paw ----------------------------------------------------
    extra = [-3.0, -1.0, -0.5, -0.25, -0.1, 0.0, 0.1, 0.3, 1.0]
    logs = {}
    for l in sorted(pp.projectors):
        ref = list(pp.channels[l].reference_energies)
        mids = [0.5 * (a + b) for a, b in zip(ref[:-1], ref[1:])]
        energies = ref + mids + extra
        entry_l = {"energies": energies, "radius": float(pp.projector_radius(l)),
                   "values": [float(paw.log_derivative_paw(pp, l, e)) for e in energies]}
        far = float(pp.projector_radius(l)) + 0.25
        entry_l["radius_explicit"] = far
        entry_l["values_explicit"] = [float(paw.log_derivative_paw(pp, l, e, far))
                                      for e in energies[:3]]
        logs[str(l)] = entry_l
    out["log_derivative_paw"] = logs
    # paw_spectrum (default extents, 3 states) --------------------------------
    out["paw_spectrum"] = {str(l): {"n_states": 3, "stride": 2,
                                    "values": [float(x) for x in paw.paw_spectrum(pp, l, 3)]}
                           for l in sorted(pp.projectors)}
    # reconstruct_ae on an analytic smooth function ---------------------------
    rec = {}
    grid = np.linspace(0.02, 9.0, 449)
    for l in sorted(pp.projectors):
        u = grid ** (l + 1) * np.exp(-0.8 * grid)
        value = paw.reconstruct_ae(pp, l, grid, u)
        rec[str(l)] = {"recipe": "r=linspace(0.02,9.0,449); u=r**(l+1)*exp(-0.8*r)",
                       **entry(value, blobs, "l", None, samples=6)}
    out["reconstruct_ae"] = rec
    out["intruding_s_miss"] = paw.intruding_s_miss(pp)
    # local potential value and slope ----------------------------------------
    r0, rmax = float(pp.r[0]), float(pp.r[-1])
    inside = np.linspace(r0, rmax, 41)
    mixed = np.concatenate([[0.0, 0.5 * r0, r0, 1.0, 2.5], inside[1:-1],
                            [rmax, rmax * 1.0001, rmax * 1.5, 40.0, 100.0]])
    beyond = np.array([rmax * 1.01, rmax * 1.3, 40.0, 100.0])
    local = {"r0": r0, "r_max": rmax, "valence_charge": float(pp.valence_charge),
             "radii_recipe": {
                 "inside": "linspace(r0, r_max, 41)",
                 "mixed": "concat([0, 0.5*r0, r0, 1.0, 2.5], inside[1:-1], "
                          "[r_max, 1.0001*r_max, 1.5*r_max, 40.0, 100.0])",
                 "beyond": "[1.01*r_max, 1.3*r_max, 40.0, 100.0]",
                 "scalars": [0.5 * r0, 1.7, rmax * 1.2]},
             "spline": "scipy CubicSpline(r, v_local), not-a-knot; flat below r0, -Z/r beyond r_max"}
    for key, radius in (("inside", inside), ("mixed", mixed), ("beyond", beyond)):
        radius = np.asarray(radius)
        value = np.asarray(pp.local_potential(radius))
        slope = np.asarray(pp.local_potential_derivative(radius))
        if key == "inside":                    # a smooth table: digest + npz
            local["value_inside"] = entry(value, blobs, "l", None, samples=6)
            local["slope_inside"] = entry(slope, blobs, "l", None, samples=6)
        else:
            local[f"value_{key}"] = [float(x) for x in value]
            local[f"slope_{key}"] = [float(x) for x in slope]
    local["value_scalars"] = [float(pp.local_potential(x)) for x in local["radii_recipe"]["scalars"]]
    local["slope_scalars"] = [float(pp.local_potential_derivative(x)) for x in local["radii_recipe"]["scalars"]]
    out["local_potential"] = local
    # multipole moments -------------------------------------------------------
    moments = {}
    ls = sorted(pp.channels)
    for i, l1 in enumerate(ls):
        for l2 in ls[i:]:
            for L in multipole_range(l1, l2):
                if ls[-1] >= 3 and L > 2:       # f-channel sets: L <= 2 keeps the JSON small
                    continue
                for basis in ("dual", "raw"):
                    m = np.asarray(pp.multipole_moments(l1, l2, L, basis), dtype=float)
                    moments[f"{l1},{l2},{L},{basis}"] = {"shape": list(m.shape),
                                                        "values": m.reshape(-1).tolist()}
    out["multipole_moments"] = moments
    return out


def library_floor(pp, frozen: dict) -> dict:
    """Repeatability (same process, same input) and the 1-ulp sensitivity of
    the dataset-level functions: the arrays they read are moved by one ulp in
    a random direction (seed 7) and the outputs compared."""
    import copy
    import numpy as np
    from mandacaru.pseudopotentials import paw
    rng = np.random.default_rng(7)

    def moved(array):
        a = np.asarray(array, dtype=float)
        return np.nextafter(a, rng.choice([-np.inf, np.inf], size=a.shape))

    twin = copy.deepcopy(pp)
    twin.v_local_screened = moved(pp.v_local_screened)
    for l in twin.projectors:
        twin.projectors[l] = [moved(p) for p in pp.projectors[l]]
        twin.channels[l].projectors = twin.projectors[l]
    report = {"ulp_moved": "v_local_screened and every projector, one ulp, seed 7"}
    worst = {"log_derivative_paw": 0.0, "paw_spectrum": 0.0, "reconstruct_ae": 0.0}
    repeat = True
    for l in sorted(pp.projectors):
        entry_l = frozen["log_derivative_paw"][str(l)]
        for e, v in zip(entry_l["energies"], entry_l["values"]):
            base = paw.log_derivative_paw(pp, l, e)
            repeat &= (base == v)
            other = paw.log_derivative_paw(twin, l, e)
            worst["log_derivative_paw"] = max(
                worst["log_derivative_paw"], abs(other - base) / max(abs(base), 1e-300))
        spec = np.asarray(frozen["paw_spectrum"][str(l)]["values"])
        again = paw.paw_spectrum(pp, l, 3)
        repeat &= bool(np.array_equal(again, spec))
        other = paw.paw_spectrum(twin, l, 3)
        worst["paw_spectrum"] = max(worst["paw_spectrum"],
                                    float(np.max(np.abs(other - again) / np.abs(again))))
        grid = np.linspace(0.02, 9.0, 449)
        u = grid ** (l + 1) * np.exp(-0.8 * grid)
        a = paw.reconstruct_ae(pp, l, grid, u)
        b = paw.reconstruct_ae(twin, l, grid, u)
        worst["reconstruct_ae"] = max(worst["reconstruct_ae"],
                                      float(np.max(np.abs(a - b)) / np.max(np.abs(a))))
    miss = paw.intruding_s_miss(pp)
    other = paw.intruding_s_miss(twin)
    report["repeat_bitwise"] = bool(repeat and (miss == frozen["intruding_s_miss"]))
    report["max_rel_after_1ulp"] = worst
    report["intruding_s_miss_rel_after_1ulp"] = (
        None if miss is None else abs(other - miss) / max(abs(miss), 1e-300))
    report["tol_100x"] = {k: 100.0 * v for k, v in worst.items()}
    return report


