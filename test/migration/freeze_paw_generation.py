def array_table(arrays: dict, blobs: Blobs | None, points: int | None,
                full_below: int = 64) -> dict:
    """Small arrays are stored whole, large ones as fingerprints (+ blob)."""
    import numpy as np
    table = {}
    for name, array in arrays.items():
        a = np.asarray(array, dtype=float)
        if a.size <= full_below:
            table[name] = {"shape": list(a.shape),
                           "values": a.reshape(-1).tolist(),
                           "sha256": fp(a)["sha256"]}
        else:
            table[name] = entry(a, blobs, "d", points)
    return table


