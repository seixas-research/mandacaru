def infer_attempt(meta, cut, nb, first, deviates, ratio, equal_cutoffs) -> str:
    """Which ``ghost_free`` attempt label the stored construction matches
    (an inference from the file: parameters only)."""
    from mandacaru.pseudopotentials.partial_waves import (
        GHOST_REMEDY_SHIFTS, OWN_CUTOFF_SHIFTS, SHORTER_LOCAL_FACTORS)
    shift = float(meta.get("local_shift") or 0.0)
    deficit = meta.get("norm_deficit")
    if not deviates:
        return "first construction"
    unitary = deficit is not None and abs(deficit) < 1e-12
    if deviates == ["norm_deficit"] and unitary:
        return "norm_deficit=0"
    factors = [f for f in SHORTER_LOCAL_FACTORS if abs(ratio / 0.9 - f) < 0.004]
    if factors and abs(shift) < 1e-9 and unitary:
        return f"local radius x {factors[0]:g}, no shift"
    counts = sorted(set(nb.values()))
    if unitary and counts in ([9], [10]) and shift in (0.0, *OWN_CUTOFF_SHIFTS) and not equal_cutoffs:
        return f"{counts[0]} Bessel functions, shift {shift:g} (or a shorter s sphere)"
    if unitary and equal_cutoffs and shift in GHOST_REMEDY_SHIFTS and abs(ratio - 0.9) < 0.004:
        return f"balanced at {max(cut.values()):.3f} Bohr, shift {shift:g}"
    if unitary and shift in OWN_CUTOFF_SHIFTS and not equal_cutoffs:
        return f"own cutoffs, shift {shift:g}"
    return "unclassified: " + "+".join(deviates)


