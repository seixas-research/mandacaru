r"""Scalar-relativistic and Dirac radial atoms.

The non-relativistic radial equation
(:func:`~mandacaru.basis.atomic_solver.solve_radial`) is what every basis and
pseudopotential in Mandacaru was built from.  It is a poor description of a
heavy atom's core: the :math:`1s` shell of gold moves by tens of Hartree, the
valence :math:`s` levels contract and the :math:`d` levels expand, and the
:math:`p`, :math:`d` and :math:`f` channels split by the spin-orbit interaction.
This module supplies all three levels of theory through **one** radial operator.

One equation, three theories
----------------------------

Eliminating the small component from the Dirac radial pair is *exact*.  Writing
:math:`P = rg` for the large component and

.. math::

    M(r) = 1 + \frac{\varepsilon - V(r)}{2c^2}

(the local relativistic mass enhancement), the pair collapses to

.. math::

    P'' - \frac{l(l+1)}{r^2}P
        - \frac{M'}{M}\Big(P' + \frac{\kappa}{r}P\Big)
        = -2M(\varepsilon - V)P ,

where :math:`\kappa = -(l+1)` for :math:`j = l+\tfrac12` and :math:`\kappa = +l`
for :math:`j = l-\tfrac12`.  The angular momentum enters twice: through
:math:`\kappa(\kappa+1) = l(l+1)`, which is **the same for both** :math:`j`, and
through the lone :math:`\kappa M'P/(Mr)` term -- *that* term, and only that term,
is the spin-orbit interaction.

The three theories are then three values of one parameter:

=====================  =========================  ===============================
Theory                 :math:`\kappa`             Recovered by
=====================  =========================  ===============================
Non-relativistic       (any; :math:`M\equiv1`)    :math:`c\to\infty`
Scalar-relativistic    :math:`\langle\kappa\rangle = -1`  averaging over :math:`j`
Dirac                  :math:`-(l+1)` or :math:`+l`  the physical value
=====================  =========================  ===============================

The scalar-relativistic value is not a fit or a convention: the
:math:`(2j+1)`-weighted average of :math:`\kappa` over :math:`j = l\pm\tfrac12`
is

.. math::

    \langle\kappa\rangle =
      \frac{-(l+1)(2l+2) + l\,(2l)}{(2l+2) + 2l} = -1

for **every** :math:`l`, which is why Koelling and Harmon's equation
(J. Phys. C **10**, 3107 (1977)) has no :math:`l` dependence in its spin-orbit
term.  Setting :math:`\kappa = -1` therefore drops spin-orbit coupling while
keeping the mass-velocity and Darwin effects in full.  For :math:`l = 0` there
is only one :math:`j`, and :math:`\kappa = -1` *is* its physical value -- so for
s states the scalar-relativistic equation is the exact Dirac equation, which is
how ``test/basis/test_relativity.py`` pins the implementation against the
closed-form hydrogenic Dirac spectrum.

Why this form and not a first-order integration
-----------------------------------------------

Substituting :math:`P = M^{1/2}W` cancels the first-derivative term identically
(the :math:`M'` generated by differentiating :math:`M^{1/2}` is exactly the one
already there), leaving

.. math::

    W'' = \Big[\frac{l(l+1)}{r^2} + \frac{\kappa M'}{Mr}
              - \frac{M''}{2M} + \frac{3(M')^2}{4M^2}
              + 2M(V - \varepsilon)\Big] W .

That has the shape :math:`W'' = fW` that
the engine's outward Numerov integration (``models::numerov``) already integrates, so
scattering states and logarithmic derivatives come for free
(:func:`relativistic_f`), and the bound-state problem stays a **symmetric
tridiagonal eigenproblem** -- :math:`\tilde H = M^{-1/2}AM^{-1/2}` with
eigenvalue :math:`2\varepsilon` and eigenvector :math:`P` itself.  A
two-component Runge-Kutta shoot would have cost a root-find per subshell per
SCF iteration; this keeps the self-consistent atom as fast as it was.

:math:`M` depends on :math:`\varepsilon`, so the eigenproblem is solved two or
three times per state with :math:`M` rebuilt from the previous eigenvalue
(:func:`solve_radial_relativistic`); it converges geometrically because the
relativistic shift is :math:`O(c^{-2})` of the level itself.

Normalization
-------------

States are normalized :math:`\int P^2\,dr = 1`, the convention the
non-relativistic solver and everything downstream of it already use.  The small
component's share of the norm, :math:`\int F^2 dr = O((Z\alpha)^2)`, is
therefore not counted -- 5e-5 of the charge for oxygen, 4e-3 for gold, and
concentrated within the core radius where a pseudopotential replaces the
density anyway.  :func:`small_component` returns :math:`F` for the cases that
want it.
"""

from __future__ import annotations

import numpy as np

from .. import _native

#: Speed of light in atomic units -- the inverse fine-structure constant.
#: CODATA 2022: ``1/alpha = 137.035999177(21)``.
SPEED_OF_LIGHT = 137.035999177

#: The levels of theory :func:`solve_radial_relativistic` accepts.
TREATMENTS = ("none", "scalar", "dirac")

#: ``kappa`` of the scalar-relativistic (j-averaged) equation, for every l.
SCALAR_KAPPA = -1

#: Convergence of the ``M(epsilon)`` iteration, relative to the level itself
#: (with an absolute floor of the same size).  The iteration contracts by about
#: four orders of magnitude per step, so this is reached in four or five; an
#: *absolute* 1e-12 is below the last bit of a deep core level and the
#: iteration then oscillates there forever, which is why the loop also stops
#: as soon as a step fails to improve on the one before it.
ENERGY_TOLERANCE = 1e-12

#: Smallest ``M`` the square root is taken of.  ``M`` is positive wherever the
#: state has weight; this only guards the deepest grid point of a heavy atom.
MASS_FLOOR = 1e-3


# --------------------------------------------------------------------------- #
# Angular momentum bookkeeping.
# --------------------------------------------------------------------------- #

def kappa_of(l: int, j: float) -> int:
    """Dirac quantum number of the ``(l, j)`` subshell (``j = l +/- 1/2``), from the engine."""
    return int(_native.relativity_kappa_of(int(l), float(j)))


def l_of(kappa: int) -> int:
    """Orbital angular momentum of a Dirac quantum number, from the engine."""
    return int(_native.relativity_l_of(int(kappa)))


def j_of(kappa: int) -> float:
    """Total angular momentum ``j = |kappa| - 1/2``, from the engine."""
    return float(_native.relativity_j_of(int(kappa)))


def kappa_values(l: int) -> list[int]:
    """The Dirac quantum numbers of a subshell, by increasing ``j``, from the engine."""
    return list(_native.relativity_kappa_values(int(l)))


def degeneracy(kappa: int) -> int:
    """``2j + 1``, from the engine."""
    return int(_native.relativity_degeneracy(int(kappa)))


def j_average(values: dict, l: int) -> float:
    r""":math:`(2j+1)`-weighted average over the :math:`j` of one ``l``.

    ``values`` maps :math:`\kappa` to a number (an eigenvalue, a potential
    sample).  This is the combination the scalar-relativistic equation
    reproduces, and the one a spin-orbit-free pseudopotential must be built
    from.
    """
    return float(_native.relativity_j_average(dict(values), int(l)))


def spin_orbit_difference(values: dict, l: int) -> float:
    """``2/(2l+1) (eps_{l+1/2} - eps_{l-1/2})`` of ``{kappa: eps}``, from the engine."""
    return float(_native.relativity_spin_orbit_difference(dict(values), int(l)))


def hydrogenic_dirac_energy(atomic_number: float, n: int, kappa: int,
                            c: float = SPEED_OF_LIGHT) -> float:
    r"""Exact Dirac binding energy of a one-electron ion (Hartree).

    .. math::

        \varepsilon = c^2\Bigg[
            \Big(1 + \frac{(Z/c)^2}{(n_r + \gamma)^2}\Big)^{-1/2} - 1\Bigg],
        \quad n_r = n - |\kappa|,
        \quad \gamma = \sqrt{\kappa^2 - (Z/c)^2} .

    Measured from the rest mass, so it reduces to :math:`-Z^2/2n^2` as
    :math:`c\to\infty`.  It depends on :math:`n` and :math:`j` only -- the
    Dirac degeneracy of :math:`2p_{1/2}` with :math:`2s_{1/2}`.
    """
    return float(_native.relativity_hydrogenic_dirac_energy(
        float(atomic_number), int(n), int(kappa), float(c)
    ))


# --------------------------------------------------------------------------- #
# The relativistic radial operator.
# --------------------------------------------------------------------------- #

def potential_derivatives(r, potential, atomic_number: float = 0.0):
    r"""``(V', V'')`` with the Coulomb singularity differentiated in closed form.

    ``potential`` is the full :math:`V`, and ``atomic_number`` says how much of
    it is the :math:`-Z/r` nuclear term; that part contributes :math:`Z/r^2`
    and :math:`-2Z/r^3` analytically and only the smooth remainder is
    differentiated on the grid.  Taking :math:`V''` numerically through the
    singularity instead costs three digits in the 1s eigenvalue of oxygen,
    because :math:`-2Z/r^3` is 1e8 at the first grid point.

    **These do not depend on the energy**, so a self-consistent atom computes
    them once per potential and reuses them across every state and every step
    of the :math:`M(\varepsilon)` iteration.
    """
    return _native.relativity_potential_derivatives(
        np.ascontiguousarray(r, dtype=float),
        np.ascontiguousarray(potential, dtype=float),
        float(atomic_number),
    )


def mass_factor(r, potential, energy: float, atomic_number: float = 0.0,
                c: float = SPEED_OF_LIGHT, derivatives=None):
    r"""``(M, M', M'')`` of :math:`M = 1 + (\varepsilon - V)/2c^2`.

    ``derivatives`` is an already-computed ``(V', V'')`` from
    :func:`potential_derivatives`; it is recomputed when omitted.
    """
    derivs = ((np.ascontiguousarray(derivatives[0], dtype=float),
              np.ascontiguousarray(derivatives[1], dtype=float))
             if derivatives is not None else None)
    return _native.relativity_mass_factor(
        np.ascontiguousarray(r, dtype=float), np.ascontiguousarray(potential, dtype=float),
        float(energy), float(atomic_number), float(c), derivs)


def darwin_spin_orbit_term(r, potential, kappa, M, atomic_number=0.0,
                           c=SPEED_OF_LIGHT):
    r"""``kappa M'/(Mr) - M''/(2M)``, with its singular part cancelled exactly.

    Those two terms are what carry the spin-orbit and Darwin physics, and
    written separately they are a numerical trap.  Both diverge as
    :math:`1/r^3`, and their **sum does not**:

    .. math::

        \frac{\kappa M'}{Mr} - \frac{M''}{2M}
          = \frac{1}{2c^2M}\Big[\frac{V''}{2} - \frac{\kappa V'}{r}\Big]
          = \frac{1}{2c^2M}\Big[-\frac{(1+\kappa)Z}{r^3}
              + \frac{V_s''}{2} - \frac{\kappa V_s'}{r}\Big]

    for :math:`V = -Z/r + V_s`.  The factor :math:`(1+\kappa)` kills the
    :math:`1/r^3` term **identically** at :math:`\kappa = -1` -- which is
    every s state, and every state of the scalar-relativistic equation.

    Forming the difference instead subtracts two numbers that reach 4.2e6 at
    the innermost node of a 64000-point grid and agree to 5e-8, losing seven
    digits.  It gets *worse* as the grid is refined, which is why the
    valence s eigenvalues converged erratically -- their differences grew
    rather than shrank -- while every :math:`l > 0` channel, whose wave is
    suppressed where the cancellation is bad, converged cleanly at rate 4.
    """
    return _native.relativity_darwin_spin_orbit(
        np.ascontiguousarray(r, dtype=float),
        np.ascontiguousarray(potential, dtype=float),
        int(kappa),
        np.ascontiguousarray(M, dtype=float),
        float(atomic_number),
        float(c),
    )


def relativistic_f(r, potential, l: int, kappa: int, energy: float,
                   atomic_number: float = 0.0, c: float = SPEED_OF_LIGHT,
                   treatment: str = "scalar"):
    r"""The Numerov coefficient of :math:`W'' = f\,W`.

    .. math::

        f = \frac{l(l+1)}{r^2} + \frac{\kappa M'}{Mr}
            - \frac{M''}{2M} + \frac{3(M')^2}{4M^2} + 2M(V - \varepsilon) ,

    which is :math:`2[V + l(l+1)/2r^2 - \varepsilon]` exactly when
    ``treatment="none"`` -- the same array
    the engine's radial equation builds.  The solution is
    :math:`W`; multiply by :math:`M^{1/2}` for :math:`P = rg`
    (:func:`large_component`).
    """
    return _native.relativity_f_evaluate(
        np.ascontiguousarray(r, dtype=float),
        np.ascontiguousarray(potential, dtype=float),
        int(l),
        int(kappa),
        float(energy),
        float(atomic_number),
        float(c),
        str(treatment),
    )


def spin_orbit_radial(r, potential, atomic_number: float = 0.0,
                      c: float = SPEED_OF_LIGHT, mass_corrected: bool = True,
                      energy: float = 0.0):
    r"""The radial spin-orbit function :math:`\xi(r)` of ``L . S``.

    .. math::

        \xi(r) = \frac{1}{2c^2 M(r)^2}\,\frac{1}{r}\,\frac{dV}{dr}

    so that :math:`H_{SO} = \xi(r)\,\mathbf{L}\cdot\mathbf{S}` reproduces
    the :math:`\kappa`-dependent term of the radial equation.  That identity
    is exact rather than a model: the only :math:`j` dependence left after
    eliminating the small component is :math:`-(M'/M)\kappa P/r`, and

    .. math::

        \kappa = -\big(2\,\langle\mathbf{L}\cdot\mathbf{S}\rangle + 1\big)

    for both :math:`j`, so the part of that term which distinguishes them is
    proportional to :math:`\mathbf{L}\cdot\mathbf{S}`.

    ``mass_corrected`` keeps the :math:`M^{-2}` factor, which matters only
    where the potential is deep; setting it to ``False`` gives the textbook
    :math:`\frac{1}{2c^2 r}\frac{dV}{dr}` that reproduces hydrogen's
    :math:`2p` fine structure, :math:`Z^4/32c^2`, in closed form.

    The Coulomb singularity is differentiated analytically through
    :func:`potential_derivatives`, so ``atomic_number`` should say how much of
    ``potential`` is :math:`-Z/r`.
    """
    return _native.relativity_spin_orbit_radial(
        np.ascontiguousarray(r, dtype=float),
        np.ascontiguousarray(potential, dtype=float),
        float(atomic_number),
        float(c),
        bool(mass_corrected),
        float(energy),
    )


def large_component(w, M):
    r""":math:`P = M^{1/2}W` -- what the rest of the code calls ``u``."""
    return _native.relativity_large_component(
        np.ascontiguousarray(w, dtype=float), np.ascontiguousarray(M, dtype=float))


def small_component(r, P, kappa: int, M, c: float = SPEED_OF_LIGHT):
    r""":math:`F = rf`, from :math:`F = (P' + \kappa P/r)/(2cM)`.

    Exact given :math:`P`; the derivative is taken on the grid.
    """
    return _native.relativity_small_component(
        np.ascontiguousarray(r, dtype=float), np.ascontiguousarray(P, dtype=float),
        int(kappa), np.ascontiguousarray(M, dtype=float), float(c))


def _resolve(treatment: str) -> str:
    key = str(treatment).strip().lower()
    aliases = {"none": "none", "nonrelativistic": "none",
               "non-relativistic": "none", "nr": "none", "schrodinger": "none",
               "scalar": "scalar", "scalar-relativistic": "scalar",
               "sr": "scalar", "koelling-harmon": "scalar", "kh": "scalar",
               "dirac": "dirac", "full": "dirac", "relativistic": "dirac"}
    if key not in aliases:
        raise ValueError(
            f"unknown relativistic treatment {treatment!r}; "
            f"available: {', '.join(TREATMENTS)}")
    return aliases[key]


def relativistic_exchange(treatment: str) -> bool:
    """Whether a reference atom of this treatment carries the relativistic
    correction to LDA exchange (computed in Rust):
    every relativistic treatment does, the non-relativistic one does not."""
    return _resolve(treatment) != "none"


def solve_radial_relativistic(r, potential, l: int, n_nodes: int,
                              kappa: int | None = None,
                              treatment: str = "scalar",
                              atomic_number: float = 0.0,
                              energy_guess: float | None = None):
    r"""Bound state of the relativistic radial equation (native).

    Parameters
    ----------
    r, potential : ndarray
        Uniform radial grid (Bohr, strictly positive) and :math:`V(r)` on it.
    l, n_nodes : int
        Angular momentum and the number of radial nodes wanted, ``n - l - 1``.
    kappa : int, optional
        Required for ``treatment="dirac"``; ignored otherwise.
    treatment : str
        ``"none"``, ``"scalar"`` or ``"dirac"``.
    atomic_number : float
        The :math:`Z` of the :math:`-Z/r` part of ``potential``, so the Coulomb
        singularity is differentiated in closed form.
    energy_guess : float, optional
        Seeds the mass enhancement :math:`M(\varepsilon)`; the nonrelativistic level
        is used when omitted.

    Returns
    -------
    (P, eps) : (ndarray, float)
        :math:`P = rg` normalized to :math:`\int P^2 dr = 1`, positive near the
        origin, and the eigenvalue in Hartree.

    Notes
    -----
    The solve is ``mandacaru_core::models::relativity::solve_radial``: a symmetric
    tridiagonal eigenproblem rebuilt around the previous eigenvalue.  Relativistically a
    **uniform** grid cannot converge an :math:`l=0` state to better than the size of the
    correction (:math:`P \sim r^{\gamma}`, :math:`\gamma < 1`, is not analytic at the
    origin); it overstates oxygen's 1s shift by about a factor of three.  That is the
    accuracy the pseudopotential generators are built on, so it is kept.
    """
    return _native.Context(threads=1).solve_radial(
        np.ascontiguousarray(r, dtype=float),
        np.ascontiguousarray(potential, dtype=float), int(l), int(n_nodes),
        relativity=str(treatment),
        kappa=None if kappa is None else int(kappa),
        atomic_number=float(atomic_number),
        energy_guess=None if energy_guess is None else float(energy_guess))
